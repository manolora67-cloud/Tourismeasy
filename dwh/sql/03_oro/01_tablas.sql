CREATE TABLE IF NOT EXISTS ORO.DIM_MES (
    SK_MES INTEGER PRIMARY KEY,
    MES SMALLINT NOT NULL,
    NOMBRE_MES VARCHAR(12) NOT NULL,
    TRIMESTRE SMALLINT NOT NULL,
    ANIO SMALLINT NOT NULL,
    CONSTRAINT UQ_DIM_MES UNIQUE (ANIO, MES)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_TIEMPO (
    SK_TIEMPO INTEGER PRIMARY KEY,
    FECHA DATE NOT NULL UNIQUE,
    DIA SMALLINT NOT NULL,
    DIA_SEMANA VARCHAR(12) NOT NULL,
    ES_FIN_DE_SEMANA BOOLEAN NOT NULL,
    SK_MES INTEGER NOT NULL REFERENCES ORO.DIM_MES (SK_MES)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_DEPARTAMENTO (
    SK_DEPARTAMENTO SERIAL PRIMARY KEY,
    ID_DPTO VARCHAR(2) NOT NULL UNIQUE,
    NOM_DPTO VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS ORO.DIM_CIUDAD (
    SK_CIUDAD SERIAL PRIMARY KEY,
    ID_CIUDAD VARCHAR(6) NOT NULL UNIQUE,
    NOM_CIUDAD VARCHAR(40) NOT NULL,
    SK_DEPARTAMENTO INTEGER NOT NULL REFERENCES ORO.DIM_DEPARTAMENTO (SK_DEPARTAMENTO)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_TIPO_SERVICIO (
    SK_TIPO_SERVICIO SERIAL PRIMARY KEY,
    NOM_TIPO_SERVICIO VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ORO.DIM_SUBTIPO_SERVICIO (
    SK_SUBTIPO SERIAL PRIMARY KEY,
    NOM_SUBTIPO VARCHAR(100) NOT NULL,
    SK_TIPO_SERVICIO INTEGER NOT NULL REFERENCES ORO.DIM_TIPO_SERVICIO (SK_TIPO_SERVICIO),
    CONSTRAINT UQ_DIM_SUBTIPO UNIQUE (SK_TIPO_SERVICIO, NOM_SUBTIPO)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_EMPRESA (
    SK_EMPRESA BIGSERIAL PRIMARY KEY,
    ID_EMPRESA VARCHAR(10) NOT NULL,
    NOM_EMPRESA VARCHAR(50) NOT NULL,
    SK_TIPO_SERVICIO INTEGER NOT NULL REFERENCES ORO.DIM_TIPO_SERVICIO (SK_TIPO_SERVICIO),
    FECHA_INICIO TIMESTAMP NOT NULL,
    FECHA_FIN TIMESTAMP NOT NULL,
    ES_VIGENTE BOOLEAN NOT NULL,
    CONSTRAINT CK_DIM_EMPRESA_VIGENCIA
        CHECK (FECHA_FIN > FECHA_INICIO OR FECHA_FIN = TIMESTAMP '9999-12-31 00:00:00')
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_DIM_EMPRESA_VIGENTE
    ON ORO.DIM_EMPRESA (ID_EMPRESA)
    WHERE ES_VIGENTE;
CREATE INDEX IF NOT EXISTS IX_DIM_EMPRESA_VIGENCIA
    ON ORO.DIM_EMPRESA (ID_EMPRESA, FECHA_INICIO, FECHA_FIN);

CREATE TABLE IF NOT EXISTS ORO.DIM_SERVICIO (
    SK_SERVICIO BIGSERIAL PRIMARY KEY,
    ID_SERVICIO_ORIGEN VARCHAR(20) NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    ACCESIBILIDAD VARCHAR(200) NOT NULL,
    CAPACIDAD_MAX INTEGER NOT NULL,
    DURACION VARCHAR(50) NOT NULL,
    ORIGEN VARCHAR(100) NOT NULL,
    DESTINO VARCHAR(100) NOT NULL,
    SK_CIUDAD_ORIGEN INTEGER NOT NULL REFERENCES ORO.DIM_CIUDAD (SK_CIUDAD),
    SK_CIUDAD_DESTINO INTEGER NOT NULL REFERENCES ORO.DIM_CIUDAD (SK_CIUDAD),
    SK_SUBTIPO INTEGER NOT NULL REFERENCES ORO.DIM_SUBTIPO_SERVICIO (SK_SUBTIPO),
    CONSTRAINT UQ_DIM_SERVICIO UNIQUE (SK_SUBTIPO, ID_SERVICIO_ORIGEN)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_CATEGORIA_PRODUCTO (
    SK_CATEGORIA SERIAL PRIMARY KEY,
    NOM_CATEGORIA VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ORO.DIM_PRODUCTO (
    SK_PRODUCTO BIGSERIAL PRIMARY KEY,
    ID_PRODUCTO_ORIGEN INTEGER NOT NULL,
    NOM_PRODUCTO VARCHAR(100) NOT NULL,
    PROVEEDOR VARCHAR(80) NOT NULL,
    SK_CATEGORIA INTEGER NOT NULL REFERENCES ORO.DIM_CATEGORIA_PRODUCTO (SK_CATEGORIA),
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    ES_VIGENTE BOOLEAN NOT NULL,
    CONSTRAINT CK_DIM_PRODUCTO_VIGENCIA CHECK (FECHA_FIN > FECHA_INICIO),
    CONSTRAINT UQ_DIM_PRODUCTO_VERSION UNIQUE (ID_PRODUCTO_ORIGEN, FECHA_INICIO)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_DIM_PRODUCTO_VIGENTE
    ON ORO.DIM_PRODUCTO (ID_PRODUCTO_ORIGEN)
    WHERE ES_VIGENTE;
CREATE INDEX IF NOT EXISTS IX_DIM_PRODUCTO_VIGENCIA
    ON ORO.DIM_PRODUCTO (ID_PRODUCTO_ORIGEN, FECHA_INICIO, FECHA_FIN);

CREATE TABLE IF NOT EXISTS ORO.HECHO_OFERTA_TURISTICA (
    SK_TIEMPO INTEGER NOT NULL REFERENCES ORO.DIM_TIEMPO (SK_TIEMPO),
    SK_EMPRESA BIGINT NOT NULL REFERENCES ORO.DIM_EMPRESA (SK_EMPRESA),
    SK_CIUDAD INTEGER NOT NULL REFERENCES ORO.DIM_CIUDAD (SK_CIUDAD),
    SK_SERVICIO BIGINT NOT NULL REFERENCES ORO.DIM_SERVICIO (SK_SERVICIO),
    TIPO_SERVICIO_ORIGEN VARCHAR(20) NOT NULL,
    ID_SERVICIO_ORIGEN VARCHAR(20) NOT NULL,
    PRECIO NUMERIC(12,0) NOT NULL CHECK (PRECIO >= 0),
    DISPONIBLE BOOLEAN NOT NULL,
    CANTIDAD_SERVICIOS SMALLINT NOT NULL DEFAULT 1 CHECK (CANTIDAD_SERVICIOS = 1),
    PRIMARY KEY (SK_TIEMPO, TIPO_SERVICIO_ORIGEN, ID_SERVICIO_ORIGEN)
);

CREATE TABLE IF NOT EXISTS ORO.HECHO_PRODUCTO_ARTESANAL (
    SK_TIEMPO INTEGER NOT NULL REFERENCES ORO.DIM_TIEMPO (SK_TIEMPO),
    SK_CIUDAD INTEGER NOT NULL REFERENCES ORO.DIM_CIUDAD (SK_CIUDAD),
    SK_PRODUCTO BIGINT NOT NULL REFERENCES ORO.DIM_PRODUCTO (SK_PRODUCTO),
    ID_PRODUCTO_ORIGEN INTEGER NOT NULL,
    PRECIO_COP NUMERIC(10,0) NOT NULL CHECK (PRECIO_COP >= 0),
    CANTIDAD_PRODUCTOS SMALLINT NOT NULL DEFAULT 1 CHECK (CANTIDAD_PRODUCTOS = 1),
    PRIMARY KEY (SK_TIEMPO, ID_PRODUCTO_ORIGEN)
);

CREATE TABLE IF NOT EXISTS ORO.HECHO_RESENAS (
    ID_RESENA_ORIGEN NUMERIC(10,0) PRIMARY KEY,
    SK_TIEMPO INTEGER NOT NULL REFERENCES ORO.DIM_TIEMPO (SK_TIEMPO),
    PUNTUACION SMALLINT NOT NULL CHECK (PUNTUACION BETWEEN 1 AND 5),
    TOTAL_LIKES INTEGER NOT NULL CHECK (TOTAL_LIKES >= 0),
    CANTIDAD_RESENAS SMALLINT NOT NULL DEFAULT 1 CHECK (CANTIDAD_RESENAS = 1)
);

CREATE INDEX IF NOT EXISTS IX_HECHO_OFERTA_CIUDAD_FECHA ON ORO.HECHO_OFERTA_TURISTICA (SK_CIUDAD, SK_TIEMPO);
CREATE INDEX IF NOT EXISTS IX_HECHO_OFERTA_EMPRESA_FECHA ON ORO.HECHO_OFERTA_TURISTICA (SK_EMPRESA, SK_TIEMPO);
CREATE INDEX IF NOT EXISTS IX_HECHO_PRODUCTO_CIUDAD_FECHA ON ORO.HECHO_PRODUCTO_ARTESANAL (SK_CIUDAD, SK_TIEMPO);
CREATE INDEX IF NOT EXISTS IX_HECHO_RESENAS_FECHA ON ORO.HECHO_RESENAS (SK_TIEMPO);