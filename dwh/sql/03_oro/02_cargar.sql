INSERT INTO ORO.DIM_TIEMPO (SK_TIEMPO, FECHA, DIA, DIA_SEMANA, ES_FIN_DE_SEMANA, SK_MES)
SELECT
    TO_CHAR(C.FECHA, 'YYYYMMDD')::INTEGER,
    C.FECHA,
    EXTRACT(DAY FROM C.FECHA)::SMALLINT,
    CASE EXTRACT(ISODOW FROM C.FECHA)::INTEGER
        WHEN 1 THEN 'Lunes'
        WHEN 2 THEN 'Martes'
        WHEN 3 THEN 'Miercoles'
        WHEN 4 THEN 'Jueves'
        WHEN 5 THEN 'Viernes'
        WHEN 6 THEN 'Sabado'
        ELSE 'Domingo'
    END,
    EXTRACT(ISODOW FROM C.FECHA) IN (6, 7),
    EXTRACT(YEAR FROM C.FECHA)::INTEGER * 100 + EXTRACT(MONTH FROM C.FECHA)::INTEGER
FROM CALENDARIO C
ON CONFLICT (SK_TIEMPO) DO UPDATE
SET FECHA = EXCLUDED.FECHA,
    DIA = EXCLUDED.DIA,
    DIA_SEMANA = EXCLUDED.DIA_SEMANA,
    ES_FIN_DE_SEMANA = EXCLUDED.ES_FIN_DE_SEMANA,
    SK_MES = EXCLUDED.SK_MES;

-- Hecho de oferta: una fila por servicio/tipo y día.
WITH OFERTA_DIA AS (
    SELECT DISTINCT ON (O.TIPO_SERVICIO, O.ID_SERVICIO_ORIGEN, O.FECHA_SNAPSHOT)
        O.*
    FROM PLATA.OFERTA_SNAPSHOT O
    ORDER BY O.TIPO_SERVICIO, O.ID_SERVICIO_ORIGEN, O.FECHA_SNAPSHOT
),
RESUELTA AS (
    SELECT
        COALESCE(TI.SK_TIEMPO, -1) AS SK_TIEMPO,
        COALESCE(EMP.SK_EMPRESA, -1) AS SK_EMPRESA,
        COALESCE(CI.SK_CIUDAD, -1) AS SK_CIUDAD,
        COALESCE(SE.SK_SERVICIO, -1) AS SK_SERVICIO,
        O.TIPO_SERVICIO,
        O.ID_SERVICIO_ORIGEN,
        O.PRECIO,
        O.DISPONIBLE
    FROM OFERTA_DIA O
    LEFT JOIN ORO.DIM_TIEMPO TI ON TI.FECHA = O.FECHA_SNAPSHOT
    LEFT JOIN ORO.DIM_CIUDAD CI ON CI.ID_CIUDAD = O.ID_CIUDAD
    LEFT JOIN ORO.DIM_TIPO_SERVICIO TS ON TS.NOM_TIPO_SERVICIO = O.TIPO_SERVICIO
    LEFT JOIN ORO.DIM_SUBTIPO_SERVICIO ST
      ON ST.SK_TIPO_SERVICIO = TS.SK_TIPO_SERVICIO
     AND ST.NOM_SUBTIPO = O.SUBTIPO
    LEFT JOIN ORO.DIM_SERVICIO SE
      ON SE.SK_SUBTIPO = ST.SK_SUBTIPO
     AND SE.ID_SERVICIO_ORIGEN = O.ID_SERVICIO_ORIGEN
    LEFT JOIN LATERAL (
        SELECT E.SK_EMPRESA
        FROM ORO.DIM_EMPRESA E
        WHERE E.ID_EMPRESA = O.ID_EMPRESA
          AND O.FECHA_SNAPSHOT::TIMESTAMP
                + INTERVAL '1 day' - INTERVAL '1 microsecond' >= E.FECHA_INICIO
          AND O.FECHA_SNAPSHOT::TIMESTAMP
                + INTERVAL '1 day' - INTERVAL '1 microsecond' < E.FECHA_FIN
        ORDER BY E.FECHA_INICIO DESC
        LIMIT 1
    ) EMP ON TRUE
)
INSERT INTO ORO.HECHO_OFERTA_TURISTICA (
    SK_TIEMPO, SK_EMPRESA, SK_CIUDAD, SK_SERVICIO,
    TIPO_SERVICIO_ORIGEN, ID_SERVICIO_ORIGEN, PRECIO, DISPONIBLE, CANTIDAD_SERVICIOS
)
SELECT
    SK_TIEMPO, SK_EMPRESA, SK_CIUDAD, SK_SERVICIO,
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, PRECIO, DISPONIBLE, 1
FROM RESUELTA
ON CONFLICT (SK_TIEMPO, TIPO_SERVICIO_ORIGEN, ID_SERVICIO_ORIGEN) DO UPDATE
SET SK_EMPRESA = EXCLUDED.SK_EMPRESA,
    SK_CIUDAD = EXCLUDED.SK_CIUDAD,
    SK_SERVICIO = EXCLUDED.SK_SERVICIO,
    PRECIO = EXCLUDED.PRECIO,
    DISPONIBLE = EXCLUDED.DISPONIBLE,
    CANTIDAD_SERVICIOS = 1;

-- Hecho de producto: una fila por producto y fecha de fotografía.
INSERT INTO ORO.HECHO_PRODUCTO_ARTESANAL (
    SK_TIEMPO, SK_CIUDAD, SK_PRODUCTO, ID_PRODUCTO_ORIGEN,
    PRECIO_COP, CANTIDAD_PRODUCTOS
)
SELECT
    COALESCE(TI.SK_TIEMPO, -1),
    COALESCE(CI.SK_CIUDAD, -1),
    COALESCE(PR.SK_PRODUCTO, -1),
    P.ID_PRODUCTO_ORIGEN,
    P.PRECIO_COP,
    1
FROM PLATA.PRODUCTO_SNAPSHOT P
LEFT JOIN ORO.DIM_TIEMPO TI ON TI.FECHA = P.FECHA_SNAPSHOT
LEFT JOIN ORO.DIM_CIUDAD CI ON CI.ID_CIUDAD = P.ID_CIUDAD
LEFT JOIN ORO.DIM_PRODUCTO PR
  ON PR.ID_PRODUCTO_ORIGEN = P.ID_PRODUCTO_ORIGEN
 AND P.FECHA_SNAPSHOT >= PR.FECHA_INICIO
 AND P.FECHA_SNAPSHOT < PR.FECHA_FIN
ON CONFLICT (SK_TIEMPO, ID_PRODUCTO_ORIGEN) DO UPDATE
