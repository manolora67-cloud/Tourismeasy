INSERT INTO ORO.HECHO_RESENAS (
    ID_RESENA_ORIGEN, SK_TIEMPO, PUNTUACION, TOTAL_LIKES, CANTIDAD_RESENAS
)
SELECT
    R.ID_RESENA_ORIGEN,
    COALESCE(TI.SK_TIEMPO, -1),
    R.PUNTUACION,
    R.TOTAL_LIKES,
    1
FROM PLATA.RESENA R
LEFT JOIN ORO.DIM_TIEMPO TI ON TI.FECHA = R.FECHA_CREACION::DATE
ON CONFLICT (ID_RESENA_ORIGEN) DO UPDATE
SET SK_TIEMPO = EXCLUDED.SK_TIEMPO, PUNTUACION = EXCLUDED.PUNTUACION,
TOTAL_LIKES = EXCLUDED.TOTAL_LIKES, CANTIDAD_RESENAS = 1;
