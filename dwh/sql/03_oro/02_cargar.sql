-- Jerarquía año -> trimestre -> mes -> día.
WITH FECHAS_FUENTE AS (
    SELECT FECHA_SNAPSHOT AS FECHA FROM PLATA.OFERTA_SNAPSHOT
    UNION ALL
    SELECT FECHA_SNAPSHOT FROM PLATA.PRODUCTO_SNAPSHOT
    UNION ALL
    SELECT FECHA_CREACION::DATE FROM PLATA.RESENA
),
LIMITES AS (
    SELECT
        DATE_TRUNC('year', COALESCE(MIN(FECHA), CURRENT_DATE))::DATE AS DESDE,
        DATE_TRUNC('year', GREATEST(COALESCE(MAX(FECHA), CURRENT_DATE), CURRENT_DATE)
            + INTERVAL '1 year')::DATE - 1 AS HASTA
    FROM FECHAS_FUENTE
),
CALENDARIO AS (
    SELECT G.FECHA::DATE AS FECHA
    FROM LIMITES L
    CROSS JOIN LATERAL GENERATE_SERIES(L.DESDE, L.HASTA, INTERVAL '1 day') AS G(FECHA)
),
MESES AS (
    SELECT DISTINCT
        EXTRACT(YEAR FROM FECHA)::INTEGER * 100
            + EXTRACT(MONTH FROM FECHA)::INTEGER AS SK_MES,
        EXTRACT(MONTH FROM FECHA)::SMALLINT AS MES,
        CASE EXTRACT(MONTH FROM FECHA)::INTEGER
            WHEN 1 THEN 'Enero'
            WHEN 2 THEN 'Febrero'
            WHEN 3 THEN 'Marzo'
            WHEN 4 THEN 'Abril'
            WHEN 5 THEN 'Mayo'
            WHEN 6 THEN 'Junio'
            WHEN 7 THEN 'Julio'
            WHEN 8 THEN 'Agosto'
            WHEN 9 THEN 'Septiembre'
            WHEN 10 THEN 'Octubre'
            WHEN 11 THEN 'Noviembre'
            ELSE 'Diciembre'
        END AS NOMBRE_MES,
        EXTRACT(QUARTER FROM FECHA)::SMALLINT AS TRIMESTRE,
        EXTRACT(YEAR FROM FECHA)::SMALLINT AS ANIO
    FROM CALENDARIO
)
INSERT INTO ORO.DIM_MES (SK_MES, MES, NOMBRE_MES, TRIMESTRE, ANIO)
SELECT SK_MES, MES, NOMBRE_MES, TRIMESTRE, ANIO
FROM MESES
