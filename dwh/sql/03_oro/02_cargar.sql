CREATE TEMP TABLE PRODUCTOS_VERSIONES_CARGA ON COMMIT DROP AS
WITH PRODUCTOS_NORMALIZADOS AS (
    SELECT
        P.ID_PRODUCTO_ORIGEN,
        P.FECHA_SNAPSHOT,
        P.NOMBRE,
        P.PROVEEDOR,
        CASE
            WHEN LOWER(BTRIM(P.CATEGORIA)) IN ('talleres', 'bisuteria', 'alfareria')
                THEN LOWER(BTRIM(P.CATEGORIA))
            ELSE 'desconocido'
        END AS CATEGORIA,
        LAG(P.NOMBRE) OVER (
            PARTITION BY P.ID_PRODUCTO_ORIGEN ORDER BY P.FECHA_SNAPSHOT
        ) AS NOMBRE_ANTERIOR,
        LAG(P.PROVEEDOR) OVER (
            PARTITION BY P.ID_PRODUCTO_ORIGEN ORDER BY P.FECHA_SNAPSHOT
        ) AS PROVEEDOR_ANTERIOR,
        LAG(
            CASE
                WHEN LOWER(BTRIM(P.CATEGORIA)) IN ('talleres', 'bisuteria', 'alfareria')
                    THEN LOWER(BTRIM(P.CATEGORIA))
                ELSE 'desconocido'
            END
        ) OVER (
            PARTITION BY P.ID_PRODUCTO_ORIGEN ORDER BY P.FECHA_SNAPSHOT
        ) AS CATEGORIA_ANTERIOR
    FROM PLATA.PRODUCTO_SNAPSHOT P
),
CAMBIOS_PRODUCTO AS (
    SELECT *
    FROM PRODUCTOS_NORMALIZADOS
    WHERE NOMBRE_ANTERIOR IS NULL
       OR NOMBRE IS DISTINCT FROM NOMBRE_ANTERIOR
       OR PROVEEDOR IS DISTINCT FROM PROVEEDOR_ANTERIOR
       OR CATEGORIA IS DISTINCT FROM CATEGORIA_ANTERIOR
),
VERSIONES_PRODUCTO AS (
    SELECT
        C.*,
        COALESCE(
            LEAD(C.FECHA_SNAPSHOT) OVER (
                PARTITION BY C.ID_PRODUCTO_ORIGEN ORDER BY C.FECHA_SNAPSHOT
            ),
            DATE '9999-12-31'
        ) AS FECHA_FIN,
        LEAD(C.FECHA_SNAPSHOT) OVER (
            PARTITION BY C.ID_PRODUCTO_ORIGEN ORDER BY C.FECHA_SNAPSHOT
        ) IS NULL AS ES_VIGENTE
    FROM CAMBIOS_PRODUCTO C
)
SELECT
    V.ID_PRODUCTO_ORIGEN,
    V.FECHA_SNAPSHOT,
    V.NOMBRE,
    V.PROVEEDOR,
    V.CATEGORIA,
    V.FECHA_FIN,
    V.ES_VIGENTE
FROM VERSIONES_PRODUCTO V;

DELETE FROM ORO.DIM_PRODUCTO D
