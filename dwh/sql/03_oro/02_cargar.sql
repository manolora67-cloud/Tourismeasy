-- SCD tipo 2: cerrar solo versiones cuyo nombre o tipo cambió.
WITH EMPRESAS_FUENTE AS (
    SELECT DISTINCT ON (E.ID_EMPRESA)
        E.ID_EMPRESA,
        COALESCE(NULLIF(BTRIM(E.NOM_EMPRESA), ''), 'Desconocido') AS NOM_EMPRESA,
        CASE UPPER(BTRIM(E.TIPO_SERVICIO))
            WHEN 'HOSPEDAJE' THEN 'Hospedaje'
            WHEN 'PLANES' THEN 'Plan'
            WHEN 'TRANSPORTE' THEN 'Transporte'
            ELSE 'Desconocido'
        END AS TIPO_NOMBRE,
        E.FECHA_MODIFICACION
    FROM PLATA.EMPRESA E
    WHERE E.ID_EMPRESA <> '-1'
    ORDER BY E.ID_EMPRESA, E.FECHA_MODIFICACION DESC
),
EMPRESAS_TIPADAS AS (
    SELECT F.*, T.SK_TIPO_SERVICIO
    FROM EMPRESAS_FUENTE F
    JOIN ORO.DIM_TIPO_SERVICIO T ON T.NOM_TIPO_SERVICIO = F.TIPO_NOMBRE
)
UPDATE ORO.DIM_EMPRESA D
SET FECHA_FIN = GREATEST(
        E.FECHA_MODIFICACION,
        D.FECHA_INICIO + INTERVAL '1 second'
    ),
    ES_VIGENTE = FALSE
FROM EMPRESAS_TIPADAS E
WHERE D.ID_EMPRESA = E.ID_EMPRESA
  AND D.ES_VIGENTE
  AND (D.NOM_EMPRESA IS DISTINCT FROM E.NOM_EMPRESA
       OR D.SK_TIPO_SERVICIO IS DISTINCT FROM E.SK_TIPO_SERVICIO);

WITH EMPRESAS_FUENTE AS (
    SELECT DISTINCT ON (E.ID_EMPRESA)
        E.ID_EMPRESA,
        COALESCE(NULLIF(BTRIM(E.NOM_EMPRESA), ''), 'Desconocido') AS NOM_EMPRESA,
        CASE UPPER(BTRIM(E.TIPO_SERVICIO))
            WHEN 'HOSPEDAJE' THEN 'Hospedaje'
            WHEN 'PLANES' THEN 'Plan'
            WHEN 'TRANSPORTE' THEN 'Transporte'
            ELSE 'Desconocido'
        END AS TIPO_NOMBRE,
        COALESCE(E.FECHA_MODIFICACION, CURRENT_TIMESTAMP) AS FECHA_INICIO
    FROM PLATA.EMPRESA E
    WHERE E.ID_EMPRESA <> '-1'
    ORDER BY E.ID_EMPRESA, E.FECHA_MODIFICACION DESC
),
EMPRESAS_TIPADAS AS (
    SELECT F.*, T.SK_TIPO_SERVICIO
    FROM EMPRESAS_FUENTE F
    JOIN ORO.DIM_TIPO_SERVICIO T ON T.NOM_TIPO_SERVICIO = F.TIPO_NOMBRE
)
INSERT INTO ORO.DIM_EMPRESA (
    ID_EMPRESA, NOM_EMPRESA, SK_TIPO_SERVICIO, FECHA_INICIO, FECHA_FIN, ES_VIGENTE
)
SELECT
    E.ID_EMPRESA,
    E.NOM_EMPRESA,
    E.SK_TIPO_SERVICIO,
    GREATEST(
        E.FECHA_INICIO,
        COALESCE((
            SELECT MAX(ANTERIOR.FECHA_FIN)
            FROM ORO.DIM_EMPRESA ANTERIOR
            WHERE ANTERIOR.ID_EMPRESA = E.ID_EMPRESA
              AND NOT ANTERIOR.ES_VIGENTE
        ), E.FECHA_INICIO)
    ),
    TIMESTAMP '9999-12-31 00:00:00', TRUE
FROM EMPRESAS_TIPADAS E
WHERE NOT EXISTS (
    SELECT 1
    FROM ORO.DIM_EMPRESA ACTUAL
    WHERE ACTUAL.ID_EMPRESA = E.ID_EMPRESA
      AND ACTUAL.ES_VIGENTE
      AND ACTUAL.NOM_EMPRESA = E.NOM_EMPRESA
      AND ACTUAL.SK_TIPO_SERVICIO = E.SK_TIPO_SERVICIO
);

UPDATE ORO.DIM_EMPRESA D
SET FECHA_FIN = GREATEST(CURRENT_TIMESTAMP, D.FECHA_INICIO + INTERVAL '1 second'),
    ES_VIGENTE = FALSE
WHERE D.ES_VIGENTE
  AND D.ID_EMPRESA <> '-1'
  AND NOT EXISTS (
      SELECT 1 FROM PLATA.EMPRESA E WHERE E.ID_EMPRESA = D.ID_EMPRESA
  );

