-- Ejecutar después de copiar las fuentes a bronce.
-- Los upserts permiten volver a ejecutar la transformación sin duplicar el mismo día.
BEGIN;

TRUNCATE TABLE PLATA.EMPRESA, PLATA.RESENA;

DELETE FROM PLATA.OFERTA_SNAPSHOT WHERE FECHA_SNAPSHOT = CURRENT_DATE;
DELETE FROM PLATA.PRODUCTO_SNAPSHOT WHERE FECHA_SNAPSHOT = CURRENT_DATE;

INSERT INTO PLATA.EMPRESA (ID_EMPRESA, NOM_EMPRESA, TIPO_SERVICIO, FECHA_MODIFICACION)
SELECT ID_EMPRESA, NOM_EMPRESA, TIPO_SERVICIO, FECHA_MODIFICACION
FROM BRONCE.EMPRESAS
ON CONFLICT (ID_EMPRESA) DO UPDATE
SET NOM_EMPRESA = EXCLUDED.NOM_EMPRESA,
    TIPO_SERVICIO = EXCLUDED.TIPO_SERVICIO,
    FECHA_MODIFICACION = EXCLUDED.FECHA_MODIFICACION;

WITH OFERTAS AS (
    SELECT
        'Hospedaje'::VARCHAR AS TIPO_SERVICIO,
        H.ID_HOSPEDAJE::VARCHAR AS ID_SERVICIO_ORIGEN,
        CURRENT_DATE AS FECHA_SNAPSHOT,
        COALESCE(H.ID_EMPRESA, '-1') AS ID_EMPRESA,
        COALESCE(H.ID_CIUDAD, '-1') AS ID_CIUDAD,
        NULL::VARCHAR(6) AS ID_CIUDAD_ORIGEN,
        NULL::VARCHAR(6) AS ID_CIUDAD_DESTINO,
        COALESCE(NULLIF(BTRIM(H.TIPO_HOSPEDAJE), ''), 'Desconocido') AS SUBTIPO,
        COALESCE(NULLIF(BTRIM(H.NOM_HOSPEDAJE), ''), 'Desconocido') AS NOMBRE,
        COALESCE(NULLIF(BTRIM(H.ACCESIBILIDAD), ''), 'Desconocido') AS ACCESIBILIDAD,
        COALESCE(H.CAPACIDAD_MAX, 0)::INTEGER AS CAPACIDAD_MAX,
        'No aplica'::VARCHAR AS DURACION,
        'No aplica'::VARCHAR AS ORIGEN,
        'No aplica'::VARCHAR AS DESTINO,
        COALESCE(H.PRECIO_NOCHE, 0)::NUMERIC(12,0) AS PRECIO,
        COALESCE(H.DISPONIBILIDAD, FALSE) AS DISPONIBLE,
        0::INTEGER AS ES_HISTORICO,
        0::INTEGER AS ORDEN_FUENTE
    FROM BRONCE.HOSPEDAJE H

    UNION ALL

    SELECT
        'Hospedaje',
        COALESCE(H.DATOS_SNAPSHOT->>'id_hospedaje', H.ID_HOSPEDAJE_ORIGINAL::VARCHAR),
        COALESCE(H.FECHA_MODIFICACION::DATE, CURRENT_DATE),
        COALESCE(H.DATOS_SNAPSHOT->>'id_empresa', '-1'),
        COALESCE(H.DATOS_SNAPSHOT->>'id_ciudad', '-1'),
        NULL::VARCHAR(6),
        NULL::VARCHAR(6),
        COALESCE(NULLIF(BTRIM(H.DATOS_SNAPSHOT->>'tipo_hospedaje'), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(H.DATOS_SNAPSHOT->>'nom_hospedaje'), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(H.DATOS_SNAPSHOT->>'accesibilidad'), ''), 'Desconocido'),
        COALESCE(NULLIF(H.DATOS_SNAPSHOT->>'capacidad_max', '')::INTEGER, 0),
        'No aplica',
        'No aplica',
        'No aplica',
        COALESCE(NULLIF(H.DATOS_SNAPSHOT->>'precio_noche', '')::NUMERIC(12,0), 0),
        COALESCE(NULLIF(H.DATOS_SNAPSHOT->>'disponibilidad', '')::BOOLEAN, FALSE),
        1,
        H.ID_HIST_HOSPEDAJE
    FROM BRONCE.HISTORICO_HOSPEDAJE H
    WHERE H.DATOS_SNAPSHOT IS NOT NULL

    UNION ALL

    SELECT
        'Plan',
        P.ID_PLAN_TURISTICO::VARCHAR,
        CURRENT_DATE,
        COALESCE(P.ID_EMPRESA, '-1'),
        COALESCE(P.ID_CIUDAD, '-1'),
        NULL::VARCHAR(6),
        NULL::VARCHAR(6),
        COALESCE(NULLIF(BTRIM(TP.NOM_TIPO_PLAN), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(P.NOM_PLAN_TURISTICO), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(P.ACCESIBILIDAD), ''), 'Desconocido'),
        0,
        COALESCE(NULLIF(BTRIM(P.DURACION), ''), 'No aplica'),
        'No aplica',
        'No aplica',
        COALESCE(P.PRECIO_PLAN, 0)::NUMERIC(12,0),
        COALESCE(P.DISPONIBILIDAD, FALSE),
        0,
        0
    FROM BRONCE.PLANES_TURISTICOS P
    LEFT JOIN BRONCE.TIPOS_DE_PLAN_TURISTICO TP ON TP.ID_TIPO_PLAN = P.ID_TIPO_PLAN

    UNION ALL

    SELECT
        'Plan',
        COALESCE(P.DATOS_SNAPSHOT->>'id_plan_turistico', P.ID_PLAN_ORIGINAL::VARCHAR),
        COALESCE(P.FECHA_MODIFICACION::DATE, CURRENT_DATE),
        COALESCE(P.DATOS_SNAPSHOT->>'id_empresa', '-1'),
        COALESCE(P.DATOS_SNAPSHOT->>'id_ciudad', '-1'),
        NULL::VARCHAR(6),
        NULL::VARCHAR(6),
        COALESCE(NULLIF(BTRIM(TP.NOM_TIPO_PLAN), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(P.DATOS_SNAPSHOT->>'nom_plan_turistico'), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(P.DATOS_SNAPSHOT->>'accesibilidad'), ''), 'Desconocido'),
        0,
        COALESCE(NULLIF(BTRIM(P.DATOS_SNAPSHOT->>'duracion'), ''), 'No aplica'),
        'No aplica',
        'No aplica',
        COALESCE(NULLIF(P.DATOS_SNAPSHOT->>'precio_plan', '')::NUMERIC(12,0), 0),
        COALESCE(NULLIF(P.DATOS_SNAPSHOT->>'disponibilidad', '')::BOOLEAN, FALSE),
        1,
        P.ID_HIST_PLAN
    FROM BRONCE.HISTORICO_PLAN_TURISTICO P
    LEFT JOIN BRONCE.TIPOS_DE_PLAN_TURISTICO TP
        ON TP.ID_TIPO_PLAN = NULLIF(P.DATOS_SNAPSHOT->>'id_tipo_plan', '')::NUMERIC(2,0)
    WHERE P.DATOS_SNAPSHOT IS NOT NULL

    UNION ALL

    SELECT
        'Transporte',
        T.ID_TRANSPORTE::VARCHAR,
        CURRENT_DATE,
        COALESCE(T.ID_EMPRESA, '-1'),
        COALESCE(T.ID_CIUDAD_DESTINO, '-1'),
        T.ID_CIUDAD_ORIGEN,
        T.ID_CIUDAD_DESTINO,
        COALESCE(NULLIF(BTRIM(C.NOMBRE_CLASE), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(T.DESTINO), ''), 'Transporte sin destino'),
        'No aplica',
        0,
        'No aplica',
        COALESCE(NULLIF(BTRIM(T.ORIGEN), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(T.DESTINO), ''), 'Desconocido'),
        COALESCE(T.PRECIO, 0)::NUMERIC(12,0),
        COALESCE(T.DISPONIBILIDAD, FALSE),
        0,
        0
    FROM BRONCE.TRANSPORTE T
    LEFT JOIN BRONCE.TRANSPORTE_CLASE TC ON TC.ID_TRANSPORTE = T.ID_TRANSPORTE
    LEFT JOIN BRONCE.CLASE_SERVICIO_TRANSPORTE C ON C.ID_CLASE = TC.ID_CLASE

    UNION ALL

    SELECT
        'Transporte',
        COALESCE(T.DATOS_SNAPSHOT->>'id_transporte', T.ID_TRANSPORTE_ORIGINAL::VARCHAR),
        COALESCE(T.FECHA_MODIFICACION::DATE, CURRENT_DATE),
        COALESCE(T.DATOS_SNAPSHOT->>'id_empresa', '-1'),
        COALESCE(T.DATOS_SNAPSHOT->>'id_ciudad_destino', '-1'),
        NULLIF(T.DATOS_SNAPSHOT->>'id_ciudad_origen', ''),
        NULLIF(T.DATOS_SNAPSHOT->>'id_ciudad_destino', ''),
        COALESCE(NULLIF(BTRIM(T.DATOS_SNAPSHOT->>'nombre_clase'), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(T.DATOS_SNAPSHOT->>'destino'), ''), 'Transporte sin destino'),
        'No aplica',
        0,
        'No aplica',
        COALESCE(NULLIF(BTRIM(T.DATOS_SNAPSHOT->>'origen'), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(T.DATOS_SNAPSHOT->>'destino'), ''), 'Desconocido'),
        COALESCE(NULLIF(T.DATOS_SNAPSHOT->>'precio', '')::NUMERIC(12,0), 0),
        COALESCE(NULLIF(T.DATOS_SNAPSHOT->>'disponibilidad', '')::BOOLEAN, FALSE),
        1,
        T.ID_HIST_TRANSPORTE
    FROM BRONCE.HISTORICO_TRANSPORTE T
    WHERE T.DATOS_SNAPSHOT IS NOT NULL
),
OFERTAS_UNICAS AS (
    SELECT DISTINCT ON (TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT)
        *
    FROM OFERTAS
    ORDER BY TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT,
             ES_HISTORICO, ORDEN_FUENTE DESC
)
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO,
    SUBTIPO, NOMBRE, ACCESIBILIDAD, CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO,
    PRECIO, DISPONIBLE
)
SELECT
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO,
    SUBTIPO, NOMBRE, ACCESIBILIDAD, CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO,
    PRECIO, DISPONIBLE
FROM OFERTAS_UNICAS
ON CONFLICT (TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT) DO UPDATE
SET ID_EMPRESA = EXCLUDED.ID_EMPRESA,
    ID_CIUDAD = EXCLUDED.ID_CIUDAD,
    ID_CIUDAD_ORIGEN = EXCLUDED.ID_CIUDAD_ORIGEN,
    ID_CIUDAD_DESTINO = EXCLUDED.ID_CIUDAD_DESTINO,
    SUBTIPO = EXCLUDED.SUBTIPO,
    NOMBRE = EXCLUDED.NOMBRE,
    ACCESIBILIDAD = EXCLUDED.ACCESIBILIDAD,
    CAPACIDAD_MAX = EXCLUDED.CAPACIDAD_MAX,
    DURACION = EXCLUDED.DURACION,
    ORIGEN = EXCLUDED.ORIGEN,
    DESTINO = EXCLUDED.DESTINO,
    PRECIO = EXCLUDED.PRECIO,
    DISPONIBLE = EXCLUDED.DISPONIBLE;

WITH PRODUCTOS AS (
    SELECT
        P.ID_PRODUCTO,
        CURRENT_DATE AS FECHA_SNAPSHOT,
        COALESCE(P.ID_CIUDAD, '-1') AS ID_CIUDAD,
        COALESCE(NULLIF(LOWER(BTRIM(P.CATEGORIA)), ''), 'desconocido') AS CATEGORIA,
        COALESCE(NULLIF(BTRIM(P.NOM_PRODUCTO), ''), 'Desconocido') AS NOMBRE,
        COALESCE(NULLIF(BTRIM(P.PROVEEDOR), ''), 'Desconocido') AS PROVEEDOR,
        COALESCE(P.PRECIO_COP, 0)::NUMERIC(10,0) AS PRECIO_COP,
        0::INTEGER AS ES_HISTORICO,
        0::INTEGER AS ORDEN_FUENTE
    FROM BRONCE.PRODUCTOS_ARTESANALES P

    UNION ALL

    SELECT
        H.ID_PRODUCTO_ORIGINAL,
        COALESCE(H.FECHA_MODIFICACION::DATE, CURRENT_DATE),
        COALESCE(H.DATOS_SNAPSHOT->>'id_ciudad', '-1'),
        COALESCE(NULLIF(LOWER(BTRIM(H.DATOS_SNAPSHOT->>'categoria')), ''), 'desconocido'),
        COALESCE(NULLIF(BTRIM(H.DATOS_SNAPSHOT->>'nom_producto'), ''), 'Desconocido'),
        COALESCE(NULLIF(BTRIM(H.DATOS_SNAPSHOT->>'proveedor'), ''), 'Desconocido'),
        COALESCE(NULLIF(H.DATOS_SNAPSHOT->>'precio_cop', '')::NUMERIC(10,0), 0),
        1,
        H.ID_HIST_PRODUCTO
    FROM BRONCE.HISTORICO_PRODUCTO_ARTESANAL H
    WHERE H.DATOS_SNAPSHOT IS NOT NULL
),
PRODUCTOS_UNICOS AS (
    SELECT DISTINCT ON (ID_PRODUCTO, FECHA_SNAPSHOT)
        *
    FROM PRODUCTOS
    ORDER BY ID_PRODUCTO, FECHA_SNAPSHOT, ES_HISTORICO, ORDEN_FUENTE DESC
)
INSERT INTO PLATA.PRODUCTO_SNAPSHOT (
    ID_PRODUCTO_ORIGEN, FECHA_SNAPSHOT, ID_CIUDAD, CATEGORIA,
    NOMBRE, PROVEEDOR, PRECIO_COP
)
SELECT ID_PRODUCTO, FECHA_SNAPSHOT, ID_CIUDAD, CATEGORIA, NOMBRE, PROVEEDOR, PRECIO_COP
FROM PRODUCTOS_UNICOS
ON CONFLICT (ID_PRODUCTO_ORIGEN, FECHA_SNAPSHOT) DO UPDATE
SET ID_CIUDAD = EXCLUDED.ID_CIUDAD, CATEGORIA = EXCLUDED.CATEGORIA,
NOMBRE = EXCLUDED.NOMBRE, PROVEEDOR = EXCLUDED.PROVEEDOR, PRECIO_COP = EXCLUDED.PRECIO_COP;
INSERT INTO PLATA.RESENA (ID_RESENA_ORIGEN, FECHA_CREACION, PUNTUACION, TOTAL_LIKES)
SELECT R.ID_RESENA, R.FECHA_CREACION, R.PUNTUACION::SMALLINT, COUNT(L.ID_LIKE)::INTEGER
FROM BRONCE.RESENAS_PLATAFORMA R
LEFT JOIN BRONCE.LIKES_RESENAS L ON L.ID_RESENA = R.ID_RESENA
GROUP BY R.ID_RESENA, R.FECHA_CREACION, R.PUNTUACION
ON CONFLICT (ID_RESENA_ORIGEN) DO UPDATE
SET FECHA_CREACION = EXCLUDED.FECHA_CREACION,
PUNTUACION = EXCLUDED.PUNTUACION,
TOTAL_LIKES = EXCLUDED.TOTAL_LIKES;
COMMIT;