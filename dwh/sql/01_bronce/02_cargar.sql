-- Ejecutar dentro de la misma base PostgreSQL de TourismEasy.
-- La zona bronce es una fotografia completa y reemplazable de las fuentes seleccionadas; no contiene credenciales ni datos personales innecesarios.
BEGIN;

TRUNCATE TABLE
    BRONCE.DEPARTAMENTOS,
    BRONCE.CIUDADES,
    BRONCE.EMPRESAS,
    BRONCE.TIPOS_PLAN,
    BRONCE.CLASES_TRANSPORTE,
    BRONCE.TRANSPORTE_CLASE,
    BRONCE.HOSPEDAJE,
    BRONCE.PLANES_TURISTICOS,
    BRONCE.TRANSPORTE,
    BRONCE.PRODUCTOS_ARTESANALES,
    BRONCE.RESENAS,
    BRONCE.LIKES_RESENAS,
    BRONCE.HISTORICO_PLAN_TURISTICO,
    BRONCE.HISTORICO_HOSPEDAJE,
    BRONCE.HISTORICO_TRANSPORTE,
    BRONCE.HISTORICO_PRODUCTO_ARTESANAL;

INSERT INTO BRONCE.DEPARTAMENTOS (ID_DPTO, NOM_DPTO)
SELECT ID_DPTO, NOM_DPTO FROM PUBLIC.DEPARTAMENTOS;

INSERT INTO BRONCE.CIUDADES (ID_CIUDAD, NOM_CIUDAD, ID_DPTO)
SELECT ID_CIUDAD, NOM_CIUDAD, ID_DPTO FROM PUBLIC.CIUDADES;

INSERT INTO BRONCE.EMPRESAS (ID_EMPRESA, NOM_EMPRESA, TIPO_SERVICIO, FECHA_MODIFICACION)
SELECT ID_EMPRESA, NOM_EMPRESA, TIPO_SERVICIO, FECHA_MODIFICACION
FROM PUBLIC.EMPRESAS;

INSERT INTO BRONCE.TIPOS_PLAN (ID_TIPO_PLAN, NOM_TIPO_PLAN)
SELECT ID_TIPO_PLAN, NOM_TIPO_PLAN FROM PUBLIC.TIPOS_DE_PLAN_TURISTICO;

INSERT INTO BRONCE.CLASES_TRANSPORTE (ID_CLASE, NOMBRE_CLASE)
SELECT ID_CLASE, NOMBRE_CLASE FROM PUBLIC.CLASE_SERVICIO_TRANSPORTE;

INSERT INTO BRONCE.TRANSPORTE_CLASE (ID_TRANSPORTE, ID_CLASE)
SELECT ID_TRANSPORTE, ID_CLASE FROM PUBLIC.TRANSPORTE_CLASE;

INSERT INTO BRONCE.HOSPEDAJE (
    ID_HOSPEDAJE, ID_EMPRESA, NOM_HOSPEDAJE, TIPO_HOSPEDAJE, ID_CIUDAD,
    PRECIO_NOCHE, ACCESIBILIDAD, CAPACIDAD_MAX, DISPONIBILIDAD, FECHA_MODIFICACION
)
SELECT
    ID_HOSPEDAJE, ID_EMPRESA, NOM_HOSPEDAJE, TIPO_HOSPEDAJE, ID_CIUDAD,
    PRECIO_NOCHE, ACCESIBILIDAD, CAPACIDAD_MAX, DISPONIBILIDAD, FECHA_MODIFICACION
FROM PUBLIC.HOSPEDAJE;

INSERT INTO BRONCE.PLANES_TURISTICOS (
    ID_PLAN_TURISTICO, NOM_PLAN_TURISTICO, DURACION, ID_TIPO_PLAN,
    PRECIO_PLAN, ACCESIBILIDAD, DISPONIBILIDAD, ID_EMPRESA, ID_CIUDAD,
    FECHA_MODIFICACION
)
SELECT
    ID_PLAN_TURISTICO, NOM_PLAN_TURISTICO, DURACION, ID_TIPO_PLAN,
    PRECIO_PLAN, ACCESIBILIDAD, DISPONIBILIDAD, ID_EMPRESA, ID_CIUDAD,
    FECHA_MODIFICACION
FROM PUBLIC.PLANES_TURISTICOS;

INSERT INTO BRONCE.TRANSPORTE (
    ID_TRANSPORTE, ID_EMPRESA, ORIGEN, DESTINO, ID_CIUDAD_ORIGEN,
    ID_CIUDAD_DESTINO, PRECIO, DISPONIBILIDAD, FECHA_MODIFICACION
)
SELECT
    ID_TRANSPORTE, ID_EMPRESA, ORIGEN, DESTINO, ID_CIUDAD_ORIGEN,
    ID_CIUDAD_DESTINO, PRECIO, DISPONIBILIDAD, FECHA_MODIFICACION
FROM PUBLIC.TRANSPORTE;

INSERT INTO BRONCE.PRODUCTOS_ARTESANALES (
    ID_PRODUCTO, NOM_PRODUCTO, PROVEEDOR, CATEGORIA, PRECIO_COP,
    ID_CIUDAD, FECHA_MODIFICACION
)
SELECT
    ID_PRODUCTO, NOM_PRODUCTO, PROVEEDOR, CATEGORIA, PRECIO_COP,
    ID_CIUDAD, FECHA_MODIFICACION
FROM PUBLIC.PRODUCTOS_ARTESANALES;

INSERT INTO BRONCE.RESENAS (ID_RESENA, PUNTUACION, FECHA_CREACION)
SELECT ID_RESENA, PUNTUACION, FECHA_CREACION
FROM PUBLIC.RESENAS_PLATAFORMA;

INSERT INTO BRONCE.LIKES_RESENAS (ID_LIKE, ID_RESENA, FECHA_LIKE)
SELECT ID_LIKE, ID_RESENA, FECHA_LIKE
FROM PUBLIC.LIKES_RESENAS;

INSERT INTO BRONCE.HISTORICO_PLAN_TURISTICO (
    ID_HIST_PLAN, ID_PLAN_ORIGINAL, DATOS_SNAPSHOT, ACCION, FECHA_MODIFICACION
)
SELECT
    ID_HIST_PLAN,
    ID_PLAN_ORIGINAL,
    CASE WHEN DATOS_SNAPSHOT IS NULL THEN NULL ELSE JSONB_BUILD_OBJECT(
        'id_plan_turistico', DATOS_SNAPSHOT->>'id_plan_turistico',
        'id_empresa', DATOS_SNAPSHOT->>'id_empresa',
        'id_ciudad', DATOS_SNAPSHOT->>'id_ciudad',
        'id_tipo_plan', DATOS_SNAPSHOT->>'id_tipo_plan',
        'nom_plan_turistico', DATOS_SNAPSHOT->>'nom_plan_turistico',
        'duracion', DATOS_SNAPSHOT->>'duracion',
        'accesibilidad', DATOS_SNAPSHOT->>'accesibilidad',
        'precio_plan', DATOS_SNAPSHOT->>'precio_plan',
        'disponibilidad', DATOS_SNAPSHOT->>'disponibilidad'
    ) END,
    ACCION,
    FECHA_MODIFICACION
FROM PUBLIC.HISTORICO_PLAN_TURISTICO;

INSERT INTO BRONCE.HISTORICO_HOSPEDAJE (
    ID_HIST_HOSPEDAJE, ID_HOSPEDAJE_ORIGINAL, DATOS_SNAPSHOT, ACCION, FECHA_MODIFICACION
)
SELECT
    ID_HIST_HOSPEDAJE,
    ID_HOSPEDAJE_ORIGINAL,
    CASE WHEN DATOS_SNAPSHOT IS NULL THEN NULL ELSE JSONB_BUILD_OBJECT(
        'id_hospedaje', DATOS_SNAPSHOT->>'id_hospedaje',
        'id_empresa', DATOS_SNAPSHOT->>'id_empresa',
        'id_ciudad', DATOS_SNAPSHOT->>'id_ciudad',
        'nom_hospedaje', DATOS_SNAPSHOT->>'nom_hospedaje',
        'tipo_hospedaje', DATOS_SNAPSHOT->>'tipo_hospedaje',
        'accesibilidad', DATOS_SNAPSHOT->>'accesibilidad',
        'capacidad_max', DATOS_SNAPSHOT->>'capacidad_max',
        'precio_noche', DATOS_SNAPSHOT->>'precio_noche',
        'disponibilidad', DATOS_SNAPSHOT->>'disponibilidad'
    ) END,
    ACCION,
    FECHA_MODIFICACION
FROM PUBLIC.HISTORICO_HOSPEDAJE;

INSERT INTO BRONCE.HISTORICO_TRANSPORTE (
    ID_HIST_TRANSPORTE, ID_TRANSPORTE_ORIGINAL, DATOS_SNAPSHOT, ACCION, FECHA_MODIFICACION
)
SELECT
    ID_HIST_TRANSPORTE,
    ID_TRANSPORTE_ORIGINAL,
    CASE WHEN DATOS_SNAPSHOT IS NULL THEN NULL ELSE JSONB_BUILD_OBJECT(
        'id_transporte', DATOS_SNAPSHOT->>'id_transporte',
        'id_empresa', DATOS_SNAPSHOT->>'id_empresa',
        'origen', DATOS_SNAPSHOT->>'origen',
        'destino', DATOS_SNAPSHOT->>'destino',
        'id_ciudad_origen', DATOS_SNAPSHOT->>'id_ciudad_origen',
        'id_ciudad_destino', DATOS_SNAPSHOT->>'id_ciudad_destino',
        'id_clase', DATOS_SNAPSHOT->>'id_clase',
        'nombre_clase', DATOS_SNAPSHOT->>'nombre_clase',
        'precio', DATOS_SNAPSHOT->>'precio',
        'disponibilidad', DATOS_SNAPSHOT->>'disponibilidad'
    ) END,
    ACCION,
    FECHA_MODIFICACION
FROM PUBLIC.HISTORICO_TRANSPORTE;

INSERT INTO BRONCE.HISTORICO_PRODUCTO_ARTESANAL (
    ID_HIST_PRODUCTO, ID_PRODUCTO_ORIGINAL, DATOS_SNAPSHOT, ACCION, FECHA_MODIFICACION
)
SELECT
    ID_HIST_PRODUCTO,
    ID_PRODUCTO_ORIGINAL,
    CASE WHEN DATOS_SNAPSHOT IS NULL THEN NULL ELSE JSONB_BUILD_OBJECT(
        'id_producto', DATOS_SNAPSHOT->>'id_producto',
        'nom_producto', DATOS_SNAPSHOT->>'nom_producto',
        'proveedor', DATOS_SNAPSHOT->>'proveedor',
        'categoria', DATOS_SNAPSHOT->>'categoria',
        'precio_cop', DATOS_SNAPSHOT->>'precio_cop',
        'id_ciudad', DATOS_SNAPSHOT->>'id_ciudad'
    ) END,
    ACCION,
    FECHA_MODIFICACION
FROM PUBLIC.HISTORICO_PRODUCTO_ARTESANAL;

COMMIT;

SELECT 'departamentos' AS FUENTE, COUNT(*) AS FILAS FROM BRONCE.DEPARTAMENTOS
UNION ALL SELECT 'ciudades', COUNT(*) FROM BRONCE.CIUDADES
UNION ALL SELECT 'empresas', COUNT(*) FROM BRONCE.EMPRESAS
UNION ALL SELECT 'hospedaje', COUNT(*) FROM BRONCE.HOSPEDAJE
UNION ALL SELECT 'planes_turisticos', COUNT(*) FROM BRONCE.PLANES_TURISTICOS
UNION ALL SELECT 'transporte', COUNT(*) FROM BRONCE.TRANSPORTE
UNION ALL SELECT 'productos_artesanales', COUNT(*) FROM BRONCE.PRODUCTOS_ARTESANALES
UNION ALL SELECT 'resenas', COUNT(*) FROM BRONCE.RESENAS;