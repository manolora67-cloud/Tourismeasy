-- Zona de aterrizaje selectiva: solo fuentes analíticas y columnas permitidas.
-- No se aterrizan contraseñas, datos de contacto, comentarios ni visitor_id.

CREATE TABLE IF NOT EXISTS BRONCE.DEPARTAMENTOS (
    ID_DPTO VARCHAR(2) PRIMARY KEY,
    NOM_DPTO VARCHAR(18) NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.CIUDADES (
    ID_CIUDAD VARCHAR(6) PRIMARY KEY,
    NOM_CIUDAD VARCHAR(27) NOT NULL,
    ID_DPTO VARCHAR(2) NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.EMPRESAS (
    ID_EMPRESA VARCHAR(10) PRIMARY KEY,
    NOM_EMPRESA VARCHAR(50) NOT NULL,
    TIPO_SERVICIO VARCHAR(20) NOT NULL,
    FECHA_MODIFICACION TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.TIPOS_PLAN (
    ID_TIPO_PLAN NUMERIC(2,0) PRIMARY KEY,
    NOM_TIPO_PLAN VARCHAR(28) NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.CLASES_TRANSPORTE (
    ID_CLASE NUMERIC(10,0) PRIMARY KEY,
    NOMBRE_CLASE VARCHAR(100) NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.TRANSPORTE_CLASE (
    ID_TRANSPORTE NUMERIC(10,0) PRIMARY KEY,
    ID_CLASE NUMERIC(10,0) NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.HOSPEDAJE (
    ID_HOSPEDAJE NUMERIC(10,0) PRIMARY KEY,
    ID_EMPRESA VARCHAR(10) NOT NULL,
    NOM_HOSPEDAJE VARCHAR(100) NOT NULL,
    TIPO_HOSPEDAJE VARCHAR(30) NOT NULL,
    ID_CIUDAD VARCHAR(6) NOT NULL,
    PRECIO_NOCHE NUMERIC(12,0) NOT NULL,
    ACCESIBILIDAD VARCHAR(200) NOT NULL,
    CAPACIDAD_MAX NUMERIC(3,0) NOT NULL,
    DISPONIBILIDAD BOOLEAN NOT NULL,
    FECHA_MODIFICACION TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.PLANES_TURISTICOS (
    ID_PLAN_TURISTICO NUMERIC(10,0) PRIMARY KEY,
    NOM_PLAN_TURISTICO VARCHAR(100) NOT NULL,
    DURACION VARCHAR(50) NOT NULL,
    ID_TIPO_PLAN NUMERIC(2,0) NOT NULL,
    PRECIO_PLAN NUMERIC(12,0) NOT NULL,
    ACCESIBILIDAD VARCHAR(200) NOT NULL,
    DISPONIBILIDAD BOOLEAN NOT NULL,
    ID_EMPRESA VARCHAR(10) NOT NULL,
    ID_CIUDAD VARCHAR(6) NOT NULL,
    FECHA_MODIFICACION TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.TRANSPORTE (
    ID_TRANSPORTE NUMERIC(10,0) PRIMARY KEY,
    ID_EMPRESA VARCHAR(10) NOT NULL,
    ORIGEN VARCHAR(100) NOT NULL,
    DESTINO VARCHAR(100) NOT NULL,
    ID_CIUDAD_ORIGEN VARCHAR(6),
    ID_CIUDAD_DESTINO VARCHAR(6),
    PRECIO NUMERIC(12,0) NOT NULL,
    DISPONIBILIDAD BOOLEAN NOT NULL,
    FECHA_MODIFICACION TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.PRODUCTOS_ARTESANALES (
    ID_PRODUCTO INTEGER PRIMARY KEY,
    NOM_PRODUCTO VARCHAR(100) NOT NULL,
    PROVEEDOR VARCHAR(80) NOT NULL,
    CATEGORIA VARCHAR(20) NOT NULL,
    PRECIO_COP NUMERIC(10,0) NOT NULL,
    ID_CIUDAD VARCHAR(6) NOT NULL,
    FECHA_MODIFICACION TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.RESENAS (
    ID_RESENA NUMERIC(10,0) PRIMARY KEY,
    PUNTUACION NUMERIC(1,0) NOT NULL,
    FECHA_CREACION TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.LIKES_RESENAS (
    ID_LIKE INTEGER PRIMARY KEY,
    ID_RESENA NUMERIC(10,0) NOT NULL,
    FECHA_LIKE TIMESTAMP NOT NULL,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.HISTORICO_PLAN_TURISTICO (
    ID_HIST_PLAN INTEGER PRIMARY KEY,
    ID_PLAN_ORIGINAL NUMERIC(10,0) NOT NULL,
    DATOS_SNAPSHOT JSONB,
    ACCION VARCHAR(10),
    FECHA_MODIFICACION TIMESTAMP,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.HISTORICO_HOSPEDAJE (
    ID_HIST_HOSPEDAJE INTEGER PRIMARY KEY,
    ID_HOSPEDAJE_ORIGINAL NUMERIC(10,0) NOT NULL,
    DATOS_SNAPSHOT JSONB,
    ACCION VARCHAR(10),
    FECHA_MODIFICACION TIMESTAMP,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.HISTORICO_TRANSPORTE (
    ID_HIST_TRANSPORTE INTEGER PRIMARY KEY,
    ID_TRANSPORTE_ORIGINAL NUMERIC(10,0) NOT NULL,
    DATOS_SNAPSHOT JSONB,
    ACCION VARCHAR(10),
    FECHA_MODIFICACION TIMESTAMP,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BRONCE.HISTORICO_PRODUCTO_ARTESANAL (
    ID_HIST_PRODUCTO INTEGER PRIMARY KEY,
    ID_PRODUCTO_ORIGINAL INTEGER NOT NULL,
    DATOS_SNAPSHOT JSONB,
    ACCION VARCHAR(10),
    FECHA_MODIFICACION TIMESTAMP,
    CARGADO_EN TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
