-- Planes: Plata conserva las fotografias historicas y el estado actual.
BEGIN;

-- Reemplazar todas las fotografias de planes para no duplicarlas.
DELETE FROM PLATA.OFERTA_SNAPSHOT
WHERE TIPO_SERVICIO = 'Plan';

WITH ULTIMO_PLAN_DIA AS (
    SELECT
        ID_PLAN_ORIGINAL,
        CAST(FECHA_MODIFICACION AS DATE) AS FECHA_SNAPSHOT,
        MAX(ID_HIST_PLAN) AS ID_HIST_PLAN
    FROM BRONCE.HISTORICO_PLAN_TURISTICO
    WHERE DATOS_SNAPSHOT IS NOT NULL
      AND CAST(FECHA_MODIFICACION AS DATE) < CURRENT_DATE
    GROUP BY ID_PLAN_ORIGINAL, CAST(FECHA_MODIFICACION AS DATE)
)
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, SUBTIPO, NOMBRE, ACCESIBILIDAD,
    CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO, PRECIO, DISPONIBLE
)
SELECT
    'Plan',
    P.DATOS_SNAPSHOT->>'id_plan_turistico',
    U.FECHA_SNAPSHOT,
    P.DATOS_SNAPSHOT->>'id_empresa',
    P.DATOS_SNAPSHOT->>'id_ciudad',
    '-1',
    '-1',
    COALESCE(TRIM(TP.NOM_TIPO_PLAN), 'Desconocido'),
    TRIM(P.DATOS_SNAPSHOT->>'nom_plan_turistico'),
    TRIM(P.DATOS_SNAPSHOT->>'accesibilidad'),
    NULL,
    TRIM(P.DATOS_SNAPSHOT->>'duracion'),
    'No aplica',
    'No aplica',
    CAST(P.DATOS_SNAPSHOT->>'precio_plan' AS NUMERIC(12,0)),
    CAST(P.DATOS_SNAPSHOT->>'disponibilidad' AS BOOLEAN)
FROM ULTIMO_PLAN_DIA U
JOIN BRONCE.HISTORICO_PLAN_TURISTICO P
    ON P.ID_HIST_PLAN = U.ID_HIST_PLAN
LEFT JOIN BRONCE.TIPOS_DE_PLAN_TURISTICO TP
    ON TP.ID_TIPO_PLAN = CAST(P.DATOS_SNAPSHOT->>'id_tipo_plan' AS NUMERIC(2,0));

-- Agregar una fotografia con los datos actuales.
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, SUBTIPO, NOMBRE, ACCESIBILIDAD,
    CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO, PRECIO, DISPONIBLE
)
SELECT
    'Plan',
    CAST(P.ID_PLAN_TURISTICO AS VARCHAR),
    CURRENT_DATE,
    P.ID_EMPRESA,
    P.ID_CIUDAD,
    '-1',
    '-1',
    COALESCE(TRIM(TP.NOM_TIPO_PLAN), 'Desconocido'),
    TRIM(P.NOM_PLAN_TURISTICO),
    TRIM(P.ACCESIBILIDAD),
    NULL,
    TRIM(P.DURACION),
    'No aplica',
    'No aplica',
    CAST(P.PRECIO_PLAN AS NUMERIC(12,0)),
    P.DISPONIBILIDAD
FROM BRONCE.PLANES_TURISTICOS P
LEFT JOIN BRONCE.TIPOS_DE_PLAN_TURISTICO TP
    ON TP.ID_TIPO_PLAN = P.ID_TIPO_PLAN;

COMMIT;
