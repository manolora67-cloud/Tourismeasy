-- Transportes: Plata conserva las fotografias historicas y el estado actual.
BEGIN;

-- Reemplazar todas las fotografias de transportes para no duplicarlas.
DELETE FROM PLATA.OFERTA_SNAPSHOT
WHERE TIPO_SERVICIO = 'Transporte';

WITH ULTIMO_TRANSPORTE_DIA AS (
    SELECT
        ID_TRANSPORTE_ORIGINAL,
        CAST(FECHA_MODIFICACION AS DATE) AS FECHA_SNAPSHOT,
        MAX(ID_HIST_TRANSPORTE) AS ID_HIST_TRANSPORTE
    FROM BRONCE.HISTORICO_TRANSPORTE
    WHERE DATOS_SNAPSHOT IS NOT NULL
      AND CAST(FECHA_MODIFICACION AS DATE) < CURRENT_DATE
    GROUP BY ID_TRANSPORTE_ORIGINAL, CAST(FECHA_MODIFICACION AS DATE)
)
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, SUBTIPO, NOMBRE, ACCESIBILIDAD,
    CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO, PRECIO, DISPONIBLE
)
SELECT
    'Transporte',
    T.DATOS_SNAPSHOT->>'id_transporte',
    U.FECHA_SNAPSHOT,
    T.DATOS_SNAPSHOT->>'id_empresa',
    T.DATOS_SNAPSHOT->>'id_ciudad_destino',
    T.DATOS_SNAPSHOT->>'id_ciudad_origen',
    T.DATOS_SNAPSHOT->>'id_ciudad_destino',
    COALESCE(T.DATOS_SNAPSHOT->>'nombre_clase', 'Desconocido'),
    TRIM(T.DATOS_SNAPSHOT->>'destino'),
    'No aplica',
    NULL,
    'No aplica',
    TRIM(T.DATOS_SNAPSHOT->>'origen'),
    TRIM(T.DATOS_SNAPSHOT->>'destino'),
    CAST(T.DATOS_SNAPSHOT->>'precio' AS NUMERIC(12,0)),
    CAST(T.DATOS_SNAPSHOT->>'disponibilidad' AS BOOLEAN)
FROM ULTIMO_TRANSPORTE_DIA U
JOIN BRONCE.HISTORICO_TRANSPORTE T
    ON T.ID_HIST_TRANSPORTE = U.ID_HIST_TRANSPORTE;

-- Agregar una fotografia con los datos actuales.
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, SUBTIPO, NOMBRE, ACCESIBILIDAD,
    CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO, PRECIO, DISPONIBLE
)
SELECT
    'Transporte',
    CAST(T.ID_TRANSPORTE AS VARCHAR),
    CURRENT_DATE,
    T.ID_EMPRESA,
    T.ID_CIUDAD_DESTINO,
    T.ID_CIUDAD_ORIGEN,
    T.ID_CIUDAD_DESTINO,
    COALESCE(C.NOMBRE_CLASE, 'Desconocido'),
    TRIM(T.DESTINO),
    'No aplica',
    NULL,
    'No aplica',
    TRIM(T.ORIGEN),
    TRIM(T.DESTINO),
    CAST(T.PRECIO AS NUMERIC(12,0)),
    T.DISPONIBILIDAD
FROM BRONCE.TRANSPORTE T
LEFT JOIN BRONCE.TRANSPORTE_CLASE TC
    ON TC.ID_TRANSPORTE = T.ID_TRANSPORTE
LEFT JOIN BRONCE.CLASE_SERVICIO_TRANSPORTE C
    ON C.ID_CLASE = TC.ID_CLASE;

COMMIT;
