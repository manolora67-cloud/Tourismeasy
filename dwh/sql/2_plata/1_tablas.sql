-- =====================================================================
-- ESTRATEGIA PLATA SENCILLA: TABLAS SEPARADAS EN MODO FOTO DIARIA
-- =====================================================================

-- Tabla limpia para Empresas
CREATE TABLE IF NOT EXISTS PLATA.DIM_EMPRESAS 
(
    ID_EMPRESA          VARCHAR(10) NOT NULL,
    NOM_EMPRESA         VARCHAR(50) NOT NULL,
    TIPO_SERVICIO       VARCHAR(20) NOT NULL,
    FECHA_MODIFICACION  TIMESTAMP   NOT NULL,
    PRIMARY KEY (ID_EMPRESA),
    CONSTRAINT CHK_PLATA_EMPRESA_TIPO CHECK (TIPO_SERVICIO IN ('HOSPEDAJE', 'PLANES', 'TRANSPORTE'))
);

-- Tabla histórica sencilla para Hospedajes
CREATE TABLE IF NOT EXISTS PLATA.HIST_HOSPEDAJES 
(
    ID_HOSPEDAJE        VARCHAR(10)     NOT NULL,
    FECHA_PROCESO       DATE            NOT NULL,
    NOM_HOSPEDAJE       VARCHAR(100)    NOT NULL,
    TIPO_HOSPEDAJE      VARCHAR(30)     NOT NULL,
    ID_EMPRESA          VARCHAR(10)     NOT NULL,
    ID_CIUDAD           VARCHAR(6)      NOT NULL,
    PRECIO_NOCHE        NUMERIC(12,0)   NOT NULL,
    CAPACIDAD_MAX       INTEGER         NOT NULL,
    PRIMARY KEY (ID_HOSPEDAJE, FECHA_PROCESO),
    CONSTRAINT CHK_PLATA_HOSP_PRECIO    CHECK (PRECIO_NOCHE >= 0),
    CONSTRAINT CHK_PLATA_HOSP_CAPACIDAD CHECK (CAPACIDAD_MAX > 0)
);

-- Tabla histórica sencilla para Planes
CREATE TABLE IF NOT EXISTS PLATA.HIST_PLANES 
(
    ID_PLAN_TURISTICO   VARCHAR(10)     NOT NULL,
    FECHA_PROCESO       DATE            NOT NULL,
    NOM_PLAN_TURISTICO  VARCHAR(100)    NOT NULL,
    DURACION            VARCHAR(50)     NOT NULL,
    PRECIO_PLAN         NUMERIC(12,0)   NOT NULL,
    ID_EMPRESA          VARCHAR(10)     NOT NULL,
    ID_CIUDAD           VARCHAR(6)      NOT NULL,
    PRIMARY KEY (ID_PLAN_TURISTICO, FECHA_PROCESO),
    CONSTRAINT CHK_PLATA_PLAN_PRECIO CHECK (PRECIO_PLAN >= 0)
);

-- Tabla histórica sencilla para Transportes
CREATE TABLE IF NOT EXISTS PLATA.HIST_TRANSPORTES 
(
    ID_TRANSPORTE       VARCHAR(10)     NOT NULL,
    FECHA_PROCESO       DATE            NOT NULL,
    ID_EMPRESA          VARCHAR(10)     NOT NULL,
    ORIGEN              VARCHAR(100)    NOT NULL,
    DESTINO             VARCHAR(100)    NOT NULL,
    ID_CIUDAD_ORIGEN    VARCHAR(6)      NOT NULL,
    ID_CIUDAD_DESTINO   VARCHAR(6)      NOT NULL,
    PRECIO              NUMERIC(12,0)   NOT NULL,
    NOMBRE_CLASE        VARCHAR(100)    NOT NULL,
    PRIMARY KEY (ID_TRANSPORTE, FECHA_PROCESO),
    CONSTRAINT CHK_PLATA_TRANS_PRECIO CHECK (PRECIO >= 0)
);

-- Tabla histórica sencilla para Productos Artesanales
CREATE TABLE IF NOT EXISTS PLATA.HIST_ARTESANIAS 
(
    ID_PRODUCTO         INTEGER         NOT NULL,
    FECHA_PROCESO       DATE            NOT NULL,
    NOM_PRODUCTO        VARCHAR(100)    NOT NULL,
    PROVEEDOR           VARCHAR(80)     NOT NULL,
    CATEGORIA           VARCHAR(20)     NOT NULL,
    PRECIO_COP          NUMERIC(10,0)   NOT NULL,
    ID_CIUDAD           VARCHAR(6)      NOT NULL,
    PRIMARY KEY (ID_PRODUCTO, FECHA_PROCESO),
    CONSTRAINT CHK_PLATA_ART_PRECIO CHECK (PRECIO_COP >= 0)
);

-- Tabla histórica sencilla para Eventos de WhatsApp
CREATE TABLE IF NOT EXISTS PLATA.FACT_EVENTOS_WHATSAPP (
    ID_CLICK            SERIAL,
    ID_CLICK_ORIGEN     BIGINT NOT NULL UNIQUE,
    FECHA_HORA          TIMESTAMP NOT NULL,
    FECHA_PROCESO       DATE NOT NULL,
    ID_EMPRESA          VARCHAR(10),
    ID_PRODUCTO_ORIGEN  VARCHAR(10) NOT NULL,
    CATEGORIA           VARCHAR(20) NOT NULL,
    ID_CIUDAD           VARCHAR(6) NOT NULL,
    DISPOSITIVO         VARCHAR(255) NOT NULL,
    PRIMARY KEY (ID_CLICK, FECHA_PROCESO)
);
