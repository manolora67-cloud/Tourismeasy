CREATE TABLE IF NOT EXISTS PLATA.DIM_DEPARTAMENTOS
(
    ID_DPTO             VARCHAR(2)  NOT NULL PRIMARY KEY,
    NOM_DPTO            VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS PLATA.DIM_CIUDADES
(
    ID_CIUDAD           VARCHAR(6)  NOT NULL PRIMARY KEY,
    NOM_CIUDAD          VARCHAR(40) NOT NULL,
    ID_DPTO             VARCHAR(2)  NOT NULL
);

CREATE TABLE IF NOT EXISTS PLATA.HOSPEDAJES_DISPONIBLES
(
    ID_HOSPEDAJE        VARCHAR(10)   NOT NULL PRIMARY KEY,
    NOM_HOSPEDAJE       VARCHAR(100)  NOT NULL,
    TIPO_HOSPEDAJE      VARCHAR(30)   NOT NULL,
    ID_EMPRESA          VARCHAR(10)   NOT NULL,
    ID_CIUDAD           VARCHAR(6)    NOT NULL,
    PRECIO_NOCHE        NUMERIC(12,0) NOT NULL CHECK (PRECIO_NOCHE >= 0),
    CAPACIDAD_MAX       INTEGER       NOT NULL CHECK (CAPACIDAD_MAX > 0),
    FECHA_MODIFICACION  TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS PLATA.HIST_CAMBIOS_HOSPEDAJE
(
    ID_HIST_HOSPEDAJE   INTEGER       NOT NULL PRIMARY KEY,
    ID_HOSPEDAJE        VARCHAR(10)   NOT NULL,
    NOM_HOSPEDAJE       VARCHAR(100)  NOT NULL,
    TIPO_HOSPEDAJE      VARCHAR(30)   NOT NULL,
    ID_EMPRESA          VARCHAR(10)   NOT NULL,
    ID_CIUDAD           VARCHAR(6)    NOT NULL,
    PRECIO_NOCHE        NUMERIC(12,0) NOT NULL,
    CAPACIDAD_MAX       INTEGER       NOT NULL,
    USUARIO_REGISTRO    VARCHAR(100),
    VIGENTE_DESDE       TIMESTAMP     NOT NULL,
    VIGENTE_HASTA       TIMESTAMP     NOT NULL,
    ACCION              VARCHAR(10)   NOT NULL,
    CHECK (VIGENTE_HASTA >= VIGENTE_DESDE)
);

CREATE TABLE IF NOT EXISTS PLATA.TRANSPORTES_DISPONIBLES
