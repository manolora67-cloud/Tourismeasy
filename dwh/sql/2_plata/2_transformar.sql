-- Carga de Empresas (sobreescritura simple)
BEGIN;
TRUNCATE TABLE PLATA.DIM_EMPRESAS;
INSERT INTO PLATA.DIM_EMPRESAS
SELECT ID_EMPRESA, TRIM(NOM_EMPRESA), TRIM(TIPO_SERVICIO), FECHA_MODIFICACION
FROM BRONCE.EMPRESAS;
COMMIT;

-- Carga de Hospedajes (foto de hoy)
BEGIN;
DELETE FROM PLATA.HIST_HOSPEDAJES WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_HOSPEDAJES
SELECT
    CAST(ID_HOSPEDAJE AS VARCHAR),
    CURRENT_DATE,
    TRIM(NOM_HOSPEDAJE),
    TRIM(TIPO_HOSPEDAJE),
    ID_EMPRESA,
    ID_CIUDAD,
    CAST(PRECIO_NOCHE AS NUMERIC(12,0)),
    CAST(CAPACIDAD_MAX AS INTEGER),
    DISPONIBILIDAD
FROM BRONCE.HOSPEDAJE;
COMMIT;

-- Carga de Planes (foto de hoy)
BEGIN;
DELETE FROM PLATA.HIST_PLANES WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_PLANES
SELECT
    CAST(ID_PLAN_TURISTICO AS VARCHAR),
    CURRENT_DATE,
    TRIM(NOM_PLAN_TURISTICO),
    TRIM(DURACION),
    CAST(PRECIO_PLAN AS NUMERIC(12,0)),
    DISPONIBILIDAD,
    ID_EMPRESA,
    ID_CIUDAD
FROM BRONCE.PLANES_TURISTICOS;
COMMIT;

-- Carga de Transportes (foto de hoy con cruce simple para la clase)
BEGIN;
DELETE FROM PLATA.HIST_TRANSPORTES WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_TRANSPORTES
SELECT
    CAST(T.ID_TRANSPORTE AS VARCHAR),
    CURRENT_DATE,
    T.ID_EMPRESA,
    TRIM(T.ORIGEN),
    TRIM(T.DESTINO),
    T.ID_CIUDAD_ORIGEN,
    T.ID_CIUDAD_DESTINO,
    CAST(T.PRECIO AS NUMERIC(12,0)),
    T.DISPONIBILIDAD,
    COALESCE(C.NOMBRE_CLASE, 'Desconocido')
FROM BRONCE.TRANSPORTE T
LEFT JOIN BRONCE.TRANSPORTE_CLASE TC ON TC.ID_TRANSPORTE = T.ID_TRANSPORTE
LEFT JOIN BRONCE.CLASE_SERVICIO_TRANSPORTE C ON C.ID_CLASE = TC.ID_CLASE;
COMMIT;

-- Carga de Artesanias (foto de hoy - CORREGIDO)
BEGIN;
DELETE FROM PLATA.HIST_ARTESANIAS WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_ARTESANIAS (ID_PRODUCTO, FECHA_PROCESO, NOM_PRODUCTO, PROVEEDOR, CATEGORIA, PRECIO_COP, ID_CIUDAD)
SELECT
    P.ID_PRODUCTO,
    CURRENT_DATE, -- Agregado para cumplir con el esquema
    TRIM(P.NOM_PRODUCTO),
    TRIM(P.PROVEEDOR),
    LOWER(TRIM(P.CATEGORIA)),
    CAST(P.PRECIO_COP AS NUMERIC(10,0)),
    P.ID_CIUDAD
FROM BRONCE.PRODUCTOS_ARTESANALES P;
COMMIT;

--- Carga de Eventos de WhatsApp (foto de hoy)
BEGIN;
DELETE FROM PLATA.FACT_EVENTOS_WHATSAPP WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.FACT_EVENTOS_WHATSAPP (FECHA_HORA, FECHA_PROCESO, ID_EMPRESA, ID_PRODUCTO_ORIGEN, CATEGORIA, ID_CIUDAD, DISPOSITIVO)
SELECT
    CAST(fecha_hora AS TIMESTAMP),
    CURRENT_DATE,
    id_empresa,
    id_producto,
    tipo_categoria,
    id_ciudad,
    user_agent
FROM BRONCE.LOGS_CLICS_WEB_EXTERNOS;
COMMIT;