-- Carga de Empresas (sobreescritura simple)
BEGIN;
TRUNCATE TABLE PLATA.DIM_EMPRESAS;
INSERT INTO PLATA.DIM_EMPRESAS
SELECT ID_EMPRESA, TRIM(NOM_EMPRESA), TRIM(TIPO_SERVICIO), FECHA_MODIFICACION
FROM BRONCE.EMPRESAS;
COMMIT;

-- Carga de hospedajes disponibles (foto de hoy)
BEGIN;
DELETE FROM PLATA.HIST_HOSPEDAJES WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_HOSPEDAJES
    (ID_HOSPEDAJE, FECHA_PROCESO, NOM_HOSPEDAJE, TIPO_HOSPEDAJE, ID_EMPRESA, ID_CIUDAD, PRECIO_NOCHE, CAPACIDAD_MAX)
SELECT
    CAST(ID_HOSPEDAJE AS VARCHAR),
    CURRENT_DATE,
    TRIM(NOM_HOSPEDAJE),
    TRIM(TIPO_HOSPEDAJE),
    ID_EMPRESA,
    ID_CIUDAD,
    CAST(PRECIO_NOCHE AS NUMERIC(12,0)),
    CAST(CAPACIDAD_MAX AS INTEGER)
FROM BRONCE.HOSPEDAJE
WHERE DISPONIBILIDAD = TRUE;
COMMIT;

-- Carga de planes disponibles (foto de hoy)
BEGIN;
DELETE FROM PLATA.HIST_PLANES WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_PLANES
    (ID_PLAN_TURISTICO, FECHA_PROCESO, NOM_PLAN_TURISTICO, DURACION, PRECIO_PLAN, ID_EMPRESA, ID_CIUDAD)
SELECT
    CAST(ID_PLAN_TURISTICO AS VARCHAR),
    CURRENT_DATE,
    TRIM(NOM_PLAN_TURISTICO),
    TRIM(DURACION),
    CAST(PRECIO_PLAN AS NUMERIC(12,0)),
    ID_EMPRESA,
    ID_CIUDAD
FROM BRONCE.PLANES_TURISTICOS
