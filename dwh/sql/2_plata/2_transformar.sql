-- Plata prepara las ofertas actuales y las versiones guardadas en los historiales.
BEGIN;

TRUNCATE TABLE PLATA.DIM_CIUDADES;
INSERT INTO PLATA.DIM_CIUDADES (ID_CIUDAD, NOM_CIUDAD, ID_DPTO)
SELECT ID_CIUDAD, TRIM(NOM_CIUDAD), ID_DPTO
FROM BRONCE.CIUDADES;

TRUNCATE TABLE PLATA.DIM_DEPARTAMENTOS;
INSERT INTO PLATA.DIM_DEPARTAMENTOS (ID_DPTO, NOM_DPTO)
SELECT ID_DPTO, TRIM(NOM_DPTO)
FROM BRONCE.DEPARTAMENTOS;

TRUNCATE TABLE PLATA.ARTESANOS;
INSERT INTO PLATA.ARTESANOS (ID_ARTESANO, NOM_ARTESANO, APE_ARTESANO)
SELECT ID_PERSONA_ECOMMERCE, TRIM(NOM_PERSONA_ECOMMERCE), TRIM(APE_PERSONA_ECOMMERCE)
FROM BRONCE.PERSONAS_ECOMMERCE;

TRUNCATE TABLE PLATA.HOSPEDAJES_DISPONIBLES;
INSERT INTO PLATA.HOSPEDAJES_DISPONIBLES
    (ID_HOSPEDAJE, NOM_HOSPEDAJE, TIPO_HOSPEDAJE, ID_EMPRESA, ID_CIUDAD,
     PRECIO_NOCHE, CAPACIDAD_MAX, FECHA_MODIFICACION)
SELECT
    CAST(ID_HOSPEDAJE AS VARCHAR),
    TRIM(NOM_HOSPEDAJE),
    TRIM(TIPO_HOSPEDAJE),
    ID_EMPRESA,
    ID_CIUDAD,
    CAST(PRECIO_NOCHE AS NUMERIC(12,0)),
    CAST(CAPACIDAD_MAX AS INTEGER),
    FECHA_MODIFICACION
FROM BRONCE.HOSPEDAJE
WHERE DISPONIBILIDAD = TRUE;

TRUNCATE TABLE PLATA.HIST_CAMBIOS_HOSPEDAJE;
INSERT INTO PLATA.HIST_CAMBIOS_HOSPEDAJE
    (ID_HIST_HOSPEDAJE, ID_HOSPEDAJE, NOM_HOSPEDAJE, TIPO_HOSPEDAJE, ID_EMPRESA,
     ID_CIUDAD, PRECIO_NOCHE, CAPACIDAD_MAX, USUARIO_REGISTRO,
     VIGENTE_DESDE, VIGENTE_HASTA, ACCION)
SELECT
    H.ID_HIST_HOSPEDAJE,
    CAST(H.ID_HOSPEDAJE_ORIGINAL AS VARCHAR),
    H.DATOS_SNAPSHOT->>'nom_hospedaje',
    H.DATOS_SNAPSHOT->>'tipo_hospedaje',
    H.DATOS_SNAPSHOT->>'id_empresa',
    H.DATOS_SNAPSHOT->>'id_ciudad',
    (H.DATOS_SNAPSHOT->>'precio_noche')::NUMERIC(12,0),
    (H.DATOS_SNAPSHOT->>'capacidad_max')::INTEGER,
    H.USUARIO_RESPONSABLE,
    COALESCE(
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_modificacion', '')::TIMESTAMP,
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_creacion', '')::TIMESTAMP,
        H.FECHA_MODIFICACION
    ),
    H.FECHA_MODIFICACION,
    H.ACCION
FROM BRONCE.HISTORICO_HOSPEDAJE H
WHERE H.DATOS_SNAPSHOT->>'disponibilidad' = 'true';

TRUNCATE TABLE PLATA.TRANSPORTES_DISPONIBLES;
INSERT INTO PLATA.TRANSPORTES_DISPONIBLES
    (ID_TRANSPORTE, ID_EMPRESA, ORIGEN, DESTINO, ID_CIUDAD_ORIGEN,
     ID_CIUDAD_DESTINO, FECHA_SALIDA, HORA_SALIDA, PRECIO,
     ID_CLASE, NOMBRE_CLASE, FECHA_MODIFICACION)
SELECT
    CAST(T.ID_TRANSPORTE AS VARCHAR),
    T.ID_EMPRESA,
    TRIM(T.ORIGEN),
    TRIM(T.DESTINO),
    T.ID_CIUDAD_ORIGEN,
    T.ID_CIUDAD_DESTINO,
    T.FECHA_SALIDA,
    T.HORA_SALIDA,
    CAST(T.PRECIO AS NUMERIC(12,0)),
    CAST(C.ID_CLASE AS VARCHAR),
    TRIM(C.NOMBRE_CLASE),
    T.FECHA_MODIFICACION
FROM BRONCE.TRANSPORTE T
LEFT JOIN BRONCE.TRANSPORTE_CLASE TC ON TC.ID_TRANSPORTE = T.ID_TRANSPORTE
LEFT JOIN BRONCE.CLASE_SERVICIO_TRANSPORTE C ON C.ID_CLASE = TC.ID_CLASE
WHERE T.DISPONIBILIDAD = TRUE;

TRUNCATE TABLE PLATA.HIST_CAMBIOS_TRANSPORTE;
INSERT INTO PLATA.HIST_CAMBIOS_TRANSPORTE
    (ID_HIST_TRANSPORTE, ID_TRANSPORTE, ID_EMPRESA, ORIGEN, DESTINO,
     ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, FECHA_SALIDA, HORA_SALIDA, PRECIO,
     ID_CLASE, NOMBRE_CLASE, USUARIO_REGISTRO, VIGENTE_DESDE, VIGENTE_HASTA, ACCION)
SELECT
    H.ID_HIST_TRANSPORTE,
    CAST(H.ID_TRANSPORTE_ORIGINAL AS VARCHAR),
    H.DATOS_SNAPSHOT->>'id_empresa',
    H.DATOS_SNAPSHOT->>'origen',
    H.DATOS_SNAPSHOT->>'destino',
    H.DATOS_SNAPSHOT->>'id_ciudad_origen',
    H.DATOS_SNAPSHOT->>'id_ciudad_destino',
    (H.DATOS_SNAPSHOT->>'fecha_salida')::DATE,
    (H.DATOS_SNAPSHOT->>'hora_salida')::TIME,
    (H.DATOS_SNAPSHOT->>'precio')::NUMERIC(12,0),
    H.DATOS_SNAPSHOT->>'id_clase',
    H.DATOS_SNAPSHOT->>'nombre_clase',
    H.USUARIO_RESPONSABLE,
    COALESCE(
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_modificacion', '')::TIMESTAMP,
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_creacion', '')::TIMESTAMP,
        H.FECHA_MODIFICACION
    ),
    H.FECHA_MODIFICACION,
    H.ACCION
FROM BRONCE.HISTORICO_TRANSPORTE H
WHERE H.DATOS_SNAPSHOT->>'disponibilidad' = 'true';

TRUNCATE TABLE PLATA.PLANES_DISPONIBLES;
INSERT INTO PLATA.PLANES_DISPONIBLES
    (ID_PLAN_TURISTICO, NOM_PLAN_TURISTICO, DURACION, INCLUYE,
     ID_TIPO_PLAN, NOM_TIPO_PLAN, PRECIO_PLAN, ID_EMPRESA, ID_CIUDAD,
     FECHA_MODIFICACION)
SELECT
    CAST(P.ID_PLAN_TURISTICO AS VARCHAR),
    TRIM(P.NOM_PLAN_TURISTICO),
    TRIM(P.DURACION),
    TRIM(P.INCLUYE),
    CAST(P.ID_TIPO_PLAN AS VARCHAR),
    TRIM(T.NOM_TIPO_PLAN),
    CAST(P.PRECIO_PLAN AS NUMERIC(12,0)),
    P.ID_EMPRESA,
    P.ID_CIUDAD,
    P.FECHA_MODIFICACION
FROM BRONCE.PLANES_TURISTICOS P
JOIN BRONCE.TIPOS_DE_PLAN_TURISTICO T ON T.ID_TIPO_PLAN = P.ID_TIPO_PLAN
WHERE P.DISPONIBILIDAD = TRUE;

TRUNCATE TABLE PLATA.HIST_CAMBIOS_PLAN;
INSERT INTO PLATA.HIST_CAMBIOS_PLAN
    (ID_HIST_PLAN, ID_PLAN_TURISTICO, NOM_PLAN_TURISTICO, DURACION, INCLUYE,
     ID_TIPO_PLAN, NOM_TIPO_PLAN, PRECIO_PLAN, ID_EMPRESA, ID_CIUDAD,
     USUARIO_REGISTRO, VIGENTE_DESDE, VIGENTE_HASTA, ACCION)
SELECT
    H.ID_HIST_PLAN,
    CAST(H.ID_PLAN_ORIGINAL AS VARCHAR),
    H.DATOS_SNAPSHOT->>'nom_plan_turistico',
    H.DATOS_SNAPSHOT->>'duracion',
    H.DATOS_SNAPSHOT->>'incluye',
    H.DATOS_SNAPSHOT->>'id_tipo_plan',
    T.NOM_TIPO_PLAN,
    (H.DATOS_SNAPSHOT->>'precio_plan')::NUMERIC(12,0),
    H.DATOS_SNAPSHOT->>'id_empresa',
    H.DATOS_SNAPSHOT->>'id_ciudad',
    H.USUARIO_RESPONSABLE,
    COALESCE(
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_modificacion', '')::TIMESTAMP,
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_creacion', '')::TIMESTAMP,
        H.FECHA_MODIFICACION
    ),
    H.FECHA_MODIFICACION,
    H.ACCION
FROM BRONCE.HISTORICO_PLAN_TURISTICO H
LEFT JOIN BRONCE.TIPOS_DE_PLAN_TURISTICO T
  ON T.ID_TIPO_PLAN::TEXT = H.DATOS_SNAPSHOT->>'id_tipo_plan'
WHERE H.DATOS_SNAPSHOT->>'disponibilidad' = 'true';

TRUNCATE TABLE PLATA.PRODUCTOS_ARTESANALES;
INSERT INTO PLATA.PRODUCTOS_ARTESANALES
    (ID_PRODUCTO, NOM_PRODUCTO, PROVEEDOR, CATEGORIA, PRECIO_COP,
     ID_CIUDAD, ID_ARTESANO, FECHA_MODIFICACION)
SELECT
    CAST(P.ID_PRODUCTO AS VARCHAR),
    TRIM(P.NOM_PRODUCTO),
    TRIM(P.PROVEEDOR),
    TRIM(P.CATEGORIA),
    CAST(P.PRECIO_COP AS NUMERIC(10,0)),
    P.ID_CIUDAD,
    P.ID_PERSONA_ECOMMERCE,
    P.FECHA_MODIFICACION
FROM BRONCE.PRODUCTOS_ARTESANALES P;

TRUNCATE TABLE PLATA.HIST_CAMBIOS_PRODUCTO;
INSERT INTO PLATA.HIST_CAMBIOS_PRODUCTO
    (ID_HIST_PRODUCTO, ID_PRODUCTO, NOM_PRODUCTO, PROVEEDOR, CATEGORIA,
     PRECIO_COP, ID_CIUDAD, ID_ARTESANO, USUARIO_REGISTRO,
     VIGENTE_DESDE, VIGENTE_HASTA, ACCION)
SELECT
    H.ID_HIST_PRODUCTO,
    CAST(H.ID_PRODUCTO_ORIGINAL AS VARCHAR),
    H.DATOS_SNAPSHOT->>'nom_producto',
    H.DATOS_SNAPSHOT->>'proveedor',
    H.DATOS_SNAPSHOT->>'categoria',
    (H.DATOS_SNAPSHOT->>'precio_cop')::NUMERIC(10,0),
    H.DATOS_SNAPSHOT->>'id_ciudad',
    H.DATOS_SNAPSHOT->>'id_persona_ecommerce',
    H.USUARIO_RESPONSABLE,
    COALESCE(
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_modificacion', '')::TIMESTAMP,
        NULLIF(H.DATOS_SNAPSHOT->>'fecha_registro', '')::TIMESTAMP,
        H.FECHA_MODIFICACION
    ),
    H.FECHA_MODIFICACION,
    H.ACCION
FROM BRONCE.HISTORICO_PRODUCTO_ARTESANAL H;

COMMIT;
