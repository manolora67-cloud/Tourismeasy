COMMIT;

-- Carga de transportes disponibles (foto de hoy con cruce simple para la clase)
BEGIN;
DELETE FROM PLATA.HIST_TRANSPORTES WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_TRANSPORTES
    (ID_TRANSPORTE, FECHA_PROCESO, ID_EMPRESA, ORIGEN, DESTINO, ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, PRECIO, NOMBRE_CLASE)
SELECT
    CAST(T.ID_TRANSPORTE AS VARCHAR),
    CURRENT_DATE,
    T.ID_EMPRESA,
    TRIM(T.ORIGEN),
    TRIM(T.DESTINO),
    T.ID_CIUDAD_ORIGEN,
    T.ID_CIUDAD_DESTINO,
    CAST(T.PRECIO AS NUMERIC(12,0)),
    COALESCE(C.NOMBRE_CLASE, 'Desconocido')
FROM BRONCE.TRANSPORTE T
LEFT JOIN BRONCE.TRANSPORTE_CLASE TC ON TC.ID_TRANSPORTE = T.ID_TRANSPORTE
LEFT JOIN BRONCE.CLASE_SERVICIO_TRANSPORTE C ON C.ID_CLASE = TC.ID_CLASE
WHERE T.DISPONIBILIDAD = TRUE;
COMMIT;

-- Carga de Artesanias (foto de hoy)
BEGIN;
DELETE FROM PLATA.HIST_ARTESANIAS WHERE FECHA_PROCESO = CURRENT_DATE;
INSERT INTO PLATA.HIST_ARTESANIAS (ID_PRODUCTO, FECHA_PROCESO, NOM_PRODUCTO, PROVEEDOR, CATEGORIA, PRECIO_COP, ID_CIUDAD)
SELECT
    P.ID_PRODUCTO,
    CURRENT_DATE, -- Agregado para cumplir con el esquema
    TRIM(P.NOM_PRODUCTO),
    TRIM(P.PROVEEDOR),
    LOWER(TRIM(P.CATEGORIA)),
    CAST(P.PRECIO_COP AS NUMERIC(10,0)),
    P.ID_CIUDAD
FROM BRONCE.PRODUCTOS_ARTESANALES P;
COMMIT;

-- Carga incremental e idempotente de Eventos de WhatsApp
BEGIN;
DELETE FROM PLATA.FACT_EVENTOS_WHATSAPP WHERE ID_CLICK_ORIGEN IS NULL;
INSERT INTO PLATA.FACT_EVENTOS_WHATSAPP (ID_CLICK_ORIGEN, FECHA_HORA, FECHA_PROCESO, ID_EMPRESA, ID_PRODUCTO_ORIGEN, CATEGORIA, ID_CIUDAD, DISPOSITIVO)
SELECT
    ID_CLICK,
    CAST(fecha_hora AS TIMESTAMP),
    CAST(fecha_hora AS DATE),
    id_empresa,
    id_producto,
    tipo_categoria,
    id_ciudad,
    user_agent
FROM BRONCE.LOGS_CLICS_WEB_EXTERNOS
ON CONFLICT (ID_CLICK_ORIGEN) DO NOTHING;
COMMIT;