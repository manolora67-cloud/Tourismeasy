-- Hospedajes: Plata conserva las fotografias historicas y el estado actual.
BEGIN;

-- Reemplazar todas las fotografias de hospedajes para no duplicarlas.
DELETE FROM PLATA.OFERTA_SNAPSHOT
WHERE TIPO_SERVICIO = 'Hospedaje';

WITH ULTIMO_HOSPEDAJE_DIA AS (
    SELECT
        ID_HOSPEDAJE_ORIGINAL,
        CAST(FECHA_MODIFICACION AS DATE) AS FECHA_SNAPSHOT,
        MAX(ID_HIST_HOSPEDAJE) AS ID_HIST_HOSPEDAJE
    FROM BRONCE.HISTORICO_HOSPEDAJE
    WHERE DATOS_SNAPSHOT IS NOT NULL
      AND CAST(FECHA_MODIFICACION AS DATE) < CURRENT_DATE
    GROUP BY ID_HOSPEDAJE_ORIGINAL, CAST(FECHA_MODIFICACION AS DATE)
)
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, SUBTIPO, NOMBRE, ACCESIBILIDAD,
    CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO, PRECIO, DISPONIBLE
)
SELECT
    'Hospedaje',
    H.DATOS_SNAPSHOT->>'id_hospedaje',
    U.FECHA_SNAPSHOT,
    H.DATOS_SNAPSHOT->>'id_empresa',
    H.DATOS_SNAPSHOT->>'id_ciudad',
    '-1',
    '-1',
    TRIM(H.DATOS_SNAPSHOT->>'tipo_hospedaje'),
    TRIM(H.DATOS_SNAPSHOT->>'nom_hospedaje'),
    TRIM(H.DATOS_SNAPSHOT->>'accesibilidad'),
    CAST(H.DATOS_SNAPSHOT->>'capacidad_max' AS INTEGER),
    'No aplica',
    'No aplica',
    'No aplica',
    CAST(H.DATOS_SNAPSHOT->>'precio_noche' AS NUMERIC(12,0)),
    CAST(H.DATOS_SNAPSHOT->>'disponibilidad' AS BOOLEAN)
FROM ULTIMO_HOSPEDAJE_DIA U
JOIN BRONCE.HISTORICO_HOSPEDAJE H
    ON H.ID_HIST_HOSPEDAJE = U.ID_HIST_HOSPEDAJE;

-- Agregar una fotografia con los datos actuales.
INSERT INTO PLATA.OFERTA_SNAPSHOT (
    TIPO_SERVICIO, ID_SERVICIO_ORIGEN, FECHA_SNAPSHOT, ID_EMPRESA, ID_CIUDAD,
    ID_CIUDAD_ORIGEN, ID_CIUDAD_DESTINO, SUBTIPO, NOMBRE, ACCESIBILIDAD,
    CAPACIDAD_MAX, DURACION, ORIGEN, DESTINO, PRECIO, DISPONIBLE
)
SELECT
    'Hospedaje',
    CAST(H.ID_HOSPEDAJE AS VARCHAR),
    CURRENT_DATE,
    H.ID_EMPRESA,
    H.ID_CIUDAD,
    '-1',
    '-1',
    TRIM(H.TIPO_HOSPEDAJE),
    TRIM(H.NOM_HOSPEDAJE),
    TRIM(H.ACCESIBILIDAD),
    CAST(H.CAPACIDAD_MAX AS INTEGER),
    'No aplica',
    'No aplica',
    'No aplica',
    CAST(H.PRECIO_NOCHE AS NUMERIC(12,0)),
    H.DISPONIBILIDAD
FROM BRONCE.HOSPEDAJE H;

COMMIT;
