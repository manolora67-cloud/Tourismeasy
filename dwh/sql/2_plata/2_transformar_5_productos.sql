-- Productos artesanales: guardar las fotografias historicas y el estado actual.
BEGIN;

-- Reemplazar las fotografias para no duplicarlas al ejecutar de nuevo.
TRUNCATE TABLE PLATA.PRODUCTO_SNAPSHOT;

WITH ULTIMO_PRODUCTO_DIA AS (
    SELECT
        ID_PRODUCTO_ORIGINAL,
        CAST(FECHA_MODIFICACION AS DATE) AS FECHA_SNAPSHOT,
        MAX(ID_HIST_PRODUCTO) AS ID_HIST_PRODUCTO
    FROM BRONCE.HISTORICO_PRODUCTO_ARTESANAL
    WHERE DATOS_SNAPSHOT IS NOT NULL
      AND CAST(FECHA_MODIFICACION AS DATE) < CURRENT_DATE
    GROUP BY ID_PRODUCTO_ORIGINAL, CAST(FECHA_MODIFICACION AS DATE)
)
INSERT INTO PLATA.PRODUCTO_SNAPSHOT (
    ID_PRODUCTO_ORIGEN, FECHA_SNAPSHOT, ID_CIUDAD,
    CATEGORIA, NOMBRE, PROVEEDOR, PRECIO_COP
)
SELECT
    H.ID_PRODUCTO_ORIGINAL,
    U.FECHA_SNAPSHOT,
    H.DATOS_SNAPSHOT->>'id_ciudad',
    LOWER(TRIM(H.DATOS_SNAPSHOT->>'categoria')),
    TRIM(H.DATOS_SNAPSHOT->>'nom_producto'),
    TRIM(H.DATOS_SNAPSHOT->>'proveedor'),
    CAST(H.DATOS_SNAPSHOT->>'precio_cop' AS NUMERIC(10,0))
FROM ULTIMO_PRODUCTO_DIA U
JOIN BRONCE.HISTORICO_PRODUCTO_ARTESANAL H
    ON H.ID_HIST_PRODUCTO = U.ID_HIST_PRODUCTO;

INSERT INTO PLATA.PRODUCTO_SNAPSHOT (
    ID_PRODUCTO_ORIGEN, FECHA_SNAPSHOT, ID_CIUDAD,
    CATEGORIA, NOMBRE, PROVEEDOR, PRECIO_COP
)
SELECT
    P.ID_PRODUCTO,
    CURRENT_DATE,
    P.ID_CIUDAD,
    LOWER(TRIM(P.CATEGORIA)),
    TRIM(P.NOM_PRODUCTO),
    TRIM(P.PROVEEDOR),
    CAST(P.PRECIO_COP AS NUMERIC(10,0))
FROM BRONCE.PRODUCTOS_ARTESANALES P;

COMMIT;
