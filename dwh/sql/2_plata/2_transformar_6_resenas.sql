-- Resenas: volver a cargarlas y contar sus likes actuales.
BEGIN;

TRUNCATE TABLE PLATA.RESENA;

INSERT INTO PLATA.RESENA (
    ID_RESENA_ORIGEN,
    FECHA_CREACION,
    PUNTUACION,
    TOTAL_LIKES
)
SELECT
    R.ID_RESENA,
    R.FECHA_CREACION,
    CAST(R.PUNTUACION AS SMALLINT),
    CAST(COUNT(L.ID_LIKE) AS INTEGER)
FROM BRONCE.RESENAS_PLATAFORMA R
LEFT JOIN BRONCE.LIKES_RESENAS L
    ON L.ID_RESENA = R.ID_RESENA
GROUP BY R.ID_RESENA, R.FECHA_CREACION, R.PUNTUACION;

COMMIT;
