-- 1. VISTA REY PARA EL AGENTE DE IA EN GROQ (Buscador Conversacional)
CREATE OR REPLACE VIEW ORO.BUSCADOR_IA_VIAJEROS AS
SELECT 
    'Hospedaje' AS TIPO_SERVICIO,
    H.ID_HOSPEDAJE AS ID_ORIGEN,
    H.NOM_HOSPEDAJE AS NOMBRE,
    H.TIPO_HOSPEDAJE AS SUBTIPO,
    E.NOM_EMPRESA AS PROVEEDOR,
    H.PRECIO_NOCHE AS PRECIO,
    C.NOM_CIUDAD AS MUNICIPIO,
    -- Aquí incluimos los requerimientos estratégicos de rangos de capacidad en texto limpio para la IA
    CASE 
        WHEN H.CAPACIDAD_MAX BETWEEN 1 AND 10 THEN 'Capacidad Pequeña (1-10 personas)'
        WHEN H.CAPACIDAD_MAX BETWEEN 11 AND 20 THEN 'Capacidad Mediana (11-20 personas)'
        ELSE 'Capacidad Grande (Más de 20 personas)'
    END AS RANGO_CAPACIDAD
FROM PLATA.HIST_HOSPEDAJES H
JOIN PLATA.DIM_EMPRESAS E ON H.ID_EMPRESA = E.ID_EMPRESA
LEFT JOIN BRONCE.CIUDADES C ON C.ID_CIUDAD = H.ID_CIUDAD
WHERE H.FECHA_PROCESO = CURRENT_DATE AND H.DISPONIBILIDAD = TRUE

UNION ALL

SELECT 
    'Plan Turístico', P.ID_PLAN_TURISTICO, P.NOM_PLAN_TURISTICO, 'Tour',
    E.NOM_EMPRESA, P.PRECIO_PLAN, C.NOM_CIUDAD, 'Duración: ' || P.DURACION
FROM PLATA.HIST_PLANES P
JOIN PLATA.DIM_EMPRESAS E ON P.ID_EMPRESA = E.ID_EMPRESA
LEFT JOIN BRONCE.CIUDADES C ON C.ID_CIUDAD = P.ID_CIUDAD
WHERE P.FECHA_PROCESO = CURRENT_DATE AND P.DISPONIBILIDAD = TRUE

UNION ALL

SELECT 
    'Transporte', T.ID_TRANSPORTE, 'Ruta ' || T.ORIGEN || ' a ' || T.DESTINO, T.NOMBRE_CLASE,
    E.NOM_EMPRESA, T.PRECIO, CD.NOM_CIUDAD, 'Ruta directa intermunicipal'
FROM PLATA.HIST_TRANSPORTES T
JOIN PLATA.DIM_EMPRESAS E ON T.ID_EMPRESA = E.ID_EMPRESA
LEFT JOIN BRONCE.CIUDADES CD ON CD.ID_CIUDAD = T.ID_CIUDAD_DESTINO
WHERE T.FECHA_PROCESO = CURRENT_DATE AND T.DISPONIBILIDAD = TRUE;


-- 2. VISTA PARA POWER BI: REPORTE DE LEADS ENVIADOS A WHATSAPP
CREATE OR REPLACE VIEW ORO.REPORTE_LEADS_WHATSAPP AS
SELECT 
    E.ID_EMPRESA, E.NOM_EMPRESA, E.TIPO_SERVICIO AS CATEGORIA_EMPRESA,
    W.CATEGORIA AS CATEGORIA_CLICK, W.FECHA_PROCESO AS FECHA,
    COUNT(W.ID_CLICK) AS TOTAL_LEADS_ENVIADOS
FROM PLATA.DIM_EMPRESAS E
JOIN PLATA.FACT_EVENTOS_WHATSAPP W ON E.ID_EMPRESA = W.ID_EMPRESA
GROUP BY E.ID_EMPRESA, E.NOM_EMPRESA, E.TIPO_SERVICIO, W.CATEGORIA, W.FECHA_PROCESO;


-- 3. VISTA PARA POWER BI: REPORTE DE ARTESANÍAS VIGENTES
CREATE OR REPLACE VIEW ORO.REPORTE_ARTESANIAS_VIGENTES AS
SELECT 
    A.ID_PRODUCTO, A.NOM_PRODUCTO, A.PROVEEDOR, A.CATEGORIA, A.PRECIO_COP, C.NOM_CIUDAD AS MUNICIPIO_ORIGEN
FROM PLATA.HIST_ARTESANIAS A
LEFT JOIN BRONCE.CIUDADES C ON C.ID_CIUDAD = A.ID_CIUDAD
WHERE A.FECHA_PROCESO = CURRENT_DATE;