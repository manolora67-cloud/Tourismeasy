-- Capa ORO: vistas analiticas sobre las tablas de PLATA.
-- Los nombres de municipios se consultan directamente en BRONCE.

CREATE SCHEMA IF NOT EXISTS ORO;

-- Catalogo disponible para el agente de IA. Cada SELECT devuelve las mismas
-- columnas para que los tres tipos de servicio se consulten juntos.
CREATE OR REPLACE VIEW ORO.BUSCADOR_IA_VIAJEROS AS
SELECT
    'Hospedaje'::VARCHAR(20) AS TIPO_SERVICIO,
    H.ID_HOSPEDAJE::VARCHAR(10) AS ID_SERVICIO,
    H.NOM_HOSPEDAJE::VARCHAR(100) AS NOMBRE,
    H.TIPO_HOSPEDAJE::VARCHAR(100) AS SUBTIPO,
    CONCAT_WS(
        ' | ',
        'Capacidad: ' || H.CAPACIDAD_MAX::VARCHAR,
        'Precio por noche: ' || H.PRECIO_NOCHE::VARCHAR
    ) AS DESCRIPCION,
    H.ID_EMPRESA,
    H.ID_CIUDAD,
    C.NOM_CIUDAD AS NOMBRE_MUNICIPIO,
    D.NOM_DPTO AS NOMBRE_DEPARTAMENTO,
    NULL::VARCHAR(27) AS MUNICIPIO_ORIGEN,
    NULL::VARCHAR(27) AS MUNICIPIO_DESTINO,
    H.PRECIO_NOCHE AS PRECIO,
    H.DISPONIBILIDAD,
    H.FECHA_PROCESO
FROM PLATA.HIST_HOSPEDAJES H
LEFT JOIN BRONCE.CIUDADES C
    ON C.ID_CIUDAD = H.ID_CIUDAD
LEFT JOIN BRONCE.DEPARTAMENTOS D
    ON D.ID_DPTO = C.ID_DPTO
WHERE H.FECHA_PROCESO = CURRENT_DATE
  AND H.DISPONIBILIDAD = TRUE

UNION ALL

SELECT
    'Plan'::VARCHAR(20),
    P.ID_PLAN_TURISTICO::VARCHAR(10),
    P.NOM_PLAN_TURISTICO::VARCHAR(100),
    'Plan turistico'::VARCHAR(100),
    'Duracion: ' || P.DURACION,
    P.ID_EMPRESA,
    P.ID_CIUDAD,
    C.NOM_CIUDAD,
    D.NOM_DPTO,
    NULL::VARCHAR(27),
    NULL::VARCHAR(27),
    P.PRECIO_PLAN,
    P.DISPONIBILIDAD,
    P.FECHA_PROCESO
FROM PLATA.HIST_PLANES P
LEFT JOIN BRONCE.CIUDADES C
    ON C.ID_CIUDAD = P.ID_CIUDAD
LEFT JOIN BRONCE.DEPARTAMENTOS D
    ON D.ID_DPTO = C.ID_DPTO
WHERE P.FECHA_PROCESO = CURRENT_DATE
  AND P.DISPONIBILIDAD = TRUE

UNION ALL

SELECT
    'Transporte'::VARCHAR(20),
    T.ID_TRANSPORTE::VARCHAR(10),
    T.ORIGEN || ' - ' || T.DESTINO,
    T.NOMBRE_CLASE,
    'Ruta: ' || T.ORIGEN || ' - ' || T.DESTINO,
    T.ID_EMPRESA,
    T.ID_CIUDAD_DESTINO,
    CD.NOM_CIUDAD,
    DD.NOM_DPTO,
    CO.NOM_CIUDAD,
    CD.NOM_CIUDAD,
    T.PRECIO,
    T.DISPONIBILIDAD,
    T.FECHA_PROCESO
FROM PLATA.HIST_TRANSPORTES T
LEFT JOIN BRONCE.CIUDADES CO
    ON CO.ID_CIUDAD = T.ID_CIUDAD_ORIGEN
LEFT JOIN BRONCE.CIUDADES CD
    ON CD.ID_CIUDAD = T.ID_CIUDAD_DESTINO
LEFT JOIN BRONCE.DEPARTAMENTOS DD
    ON DD.ID_DPTO = CD.ID_DPTO
WHERE T.FECHA_PROCESO = CURRENT_DATE
  AND T.DISPONIBILIDAD = TRUE;

-- Total de clics en WhatsApp por aliado comercial y fecha.
CREATE OR REPLACE VIEW ORO.REPORTE_LEADS_WHATSAPP AS
SELECT
    E.FECHA_PROCESO,
    E.ID_EMPRESA,
    D.NOM_EMPRESA,
    D.TIPO_SERVICIO,
    COUNT(E.ID_CLICK) AS TOTAL_LEADS
FROM PLATA.FACT_EVENTOS_WHATSAPP E
LEFT JOIN PLATA.DIM_EMPRESAS D
    ON D.ID_EMPRESA = E.ID_EMPRESA
GROUP BY
    E.FECHA_PROCESO,
    E.ID_EMPRESA,
    D.NOM_EMPRESA,
    D.TIPO_SERVICIO;

-- Catalogo actual de artesanias con el nombre del municipio de origen.
CREATE OR REPLACE VIEW ORO.REPORTE_ARTESANIAS_VIGENTES AS
SELECT
    A.ID_PRODUCTO,
    A.NOM_PRODUCTO,
    A.PROVEEDOR,
    A.CATEGORIA,
    A.PRECIO_COP,
    A.ID_CIUDAD,
    C.NOM_CIUDAD AS NOMBRE_MUNICIPIO,
    D.NOM_DPTO AS NOMBRE_DEPARTAMENTO,
    A.FECHA_PROCESO
FROM PLATA.HIST_ARTESANIAS A
LEFT JOIN BRONCE.CIUDADES C
    ON C.ID_CIUDAD = A.ID_CIUDAD
LEFT JOIN BRONCE.DEPARTAMENTOS D
    ON D.ID_DPTO = C.ID_DPTO
WHERE A.FECHA_PROCESO = CURRENT_DATE;
