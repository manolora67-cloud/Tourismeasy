FROM PLATA.HIST_CAMBIOS_PRODUCTO H
JOIN ORO.DIM_PRODUCTO_ARTESANAL D ON D.ID_HIST_PRODUCTO = H.ID_HIST_PRODUCTO
ON CONFLICT (SK_PRODUCTO) DO UPDATE SET
    PRECIO_COP = EXCLUDED.PRECIO_COP,
    ACCION_HISTORICA = EXCLUDED.ACCION_HISTORICA,
    USUARIO_REGISTRO = EXCLUDED.USUARIO_REGISTRO;

INSERT INTO ORO.HECHO_PRODUCTO_ARTESANAL (SK_PRODUCTO, PRECIO_COP)
SELECT D.SK_PRODUCTO, P.PRECIO_COP
FROM PLATA.PRODUCTOS_ARTESANALES P
JOIN ORO.DIM_PRODUCTO_ARTESANAL D
  ON D.ID_PRODUCTO = P.ID_PRODUCTO AND D.ES_ACTUAL
ON CONFLICT (SK_PRODUCTO) DO UPDATE SET
    PRECIO_COP = EXCLUDED.PRECIO_COP,
    ACCION_HISTORICA = NULL,
    USUARIO_REGISTRO = NULL;

