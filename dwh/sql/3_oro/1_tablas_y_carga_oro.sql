CREATE TABLE IF NOT EXISTS ORO.DIM_DEPARTAMENTO
(
    SK_DEPARTAMENTO     SERIAL PRIMARY KEY,
    ID_DPTO             VARCHAR(2)  NOT NULL UNIQUE,
    NOM_DEPARTAMENTO    VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS ORO.DIM_CIUDAD
(
    SK_CIUDAD           SERIAL PRIMARY KEY,
    ID_CIUDAD           VARCHAR(6)  NOT NULL UNIQUE,
    NOM_CIUDAD          VARCHAR(40) NOT NULL,
    SK_DEPARTAMENTO     INTEGER     NOT NULL REFERENCES ORO.DIM_DEPARTAMENTO(SK_DEPARTAMENTO)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_EMPRESA
(
    ID_EMPRESA          VARCHAR(10)  PRIMARY KEY,
    NOM_EMPRESA         VARCHAR(50)  NOT NULL,
    TIPO_SERVICIO       VARCHAR(20)  NOT NULL,
    ID_CIUDAD           VARCHAR(6)   NOT NULL
);

CREATE TABLE IF NOT EXISTS ORO.DIM_ARTESANO
(
    ID_ARTESANO         VARCHAR(10)  PRIMARY KEY,
    NOM_ARTESANO        VARCHAR(50)  NOT NULL,
    APE_ARTESANO        VARCHAR(50)  NOT NULL
);

CREATE TABLE IF NOT EXISTS ORO.DIM_HOSPEDAJE
(
    SK_HOSPEDAJE        SERIAL PRIMARY KEY,
    ID_HOSPEDAJE        VARCHAR(10) NOT NULL,
    ID_HIST_HOSPEDAJE   INTEGER UNIQUE,
    NOM_HOSPEDAJE       VARCHAR(100) NOT NULL,
    TIPO_HOSPEDAJE      VARCHAR(30)  NOT NULL,
    ID_EMPRESA          VARCHAR(10)  NOT NULL,
    ID_CIUDAD           VARCHAR(6)   NOT NULL,
    VIGENTE_DESDE       TIMESTAMP    NOT NULL,
    VIGENTE_HASTA       TIMESTAMP,
    ES_ACTUAL           BOOLEAN      NOT NULL,
    CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_ORO_HOSPEDAJE_ACTUAL
    ON ORO.DIM_HOSPEDAJE (ID_HOSPEDAJE)
    WHERE ES_ACTUAL;

CREATE TABLE IF NOT EXISTS ORO.DIM_TRANSPORTE
(
    SK_TRANSPORTE       SERIAL PRIMARY KEY,
    ID_TRANSPORTE       VARCHAR(10) NOT NULL,
    ID_HIST_TRANSPORTE  INTEGER UNIQUE,
    ID_EMPRESA          VARCHAR(10) NOT NULL,
    ORIGEN              VARCHAR(100) NOT NULL,
    DESTINO             VARCHAR(100) NOT NULL,
    ID_CIUDAD_ORIGEN    VARCHAR(6) NOT NULL,
    ID_CIUDAD_DESTINO   VARCHAR(6) NOT NULL,
    FECHA_SALIDA        DATE NOT NULL,
    HORA_SALIDA         TIME NOT NULL,
    ID_CLASE            VARCHAR(10),
    NOMBRE_CLASE        VARCHAR(100),
    VIGENTE_DESDE       TIMESTAMP NOT NULL,
    VIGENTE_HASTA       TIMESTAMP,
    ES_ACTUAL           BOOLEAN NOT NULL,
    CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_ORO_TRANSPORTE_ACTUAL
    ON ORO.DIM_TRANSPORTE (ID_TRANSPORTE)
    WHERE ES_ACTUAL;

CREATE TABLE IF NOT EXISTS ORO.DIM_PLAN_TURISTICO
(
    SK_PLAN_TURISTICO   SERIAL PRIMARY KEY,
    ID_PLAN_TURISTICO   VARCHAR(10) NOT NULL,
    ID_HIST_PLAN        INTEGER UNIQUE,
    NOM_PLAN_TURISTICO  VARCHAR(100) NOT NULL,
    DURACION            VARCHAR(50) NOT NULL,
