CREATE SCHEMA IF NOT EXISTS ORO;

-- 1. LIMPIEZA PREVENTIVA DE TABLAS DE HECHOS Y DIMENSIONES
TRUNCATE TABLE ORO.HECHO_OFERTA_TURISTICA CASCADE;
TRUNCATE TABLE ORO.HECHO_PRODUCTO_ARTESANAL CASCADE;
TRUNCATE TABLE ORO.HECHO_EVENTOS_WHATSAPP CASCADE;

-- 2. CREACIÓN DE DIMENSIONES GEOGRÁFICAS (Jerarquía Copo de Nieve Pura)
CREATE TABLE IF NOT EXISTS ORO.DIM_DEPARTAMENTO (
    SK_DEPARTAMENTO     SERIAL,
    ID_DPTO             VARCHAR(2)   NOT NULL UNIQUE,
    NOM_DEPARTAMENTO    VARCHAR(30)  NOT NULL,
    PRIMARY KEY (SK_DEPARTAMENTO)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_CIUDAD (
    SK_CIUDAD           SERIAL,
    ID_CIUDAD           VARCHAR(6)   NOT NULL UNIQUE,
    NOM_CIUDAD          VARCHAR(40)  NOT NULL,
    SK_DEPARTAMENTO     INTEGER      NOT NULL,
    PRIMARY KEY (SK_CIUDAD),
    FOREIGN KEY (SK_DEPARTAMENTO) REFERENCES ORO.DIM_DEPARTAMENTO(SK_DEPARTAMENTO)
);

-- 3. CREACIÓN DE DIMENSIONES DE NEGOCIO (Con Llaves SK_ Secuenciales)
CREATE TABLE IF NOT EXISTS ORO.DIM_EMPRESAS (
    SK_EMPRESA          SERIAL,
    ID_EMPRESA          VARCHAR(10) NOT NULL UNIQUE,
    NOM_EMPRESA         VARCHAR(50) NOT NULL,
    TIPO_SERVICIO       VARCHAR(20) NOT NULL,
    PRIMARY KEY (SK_EMPRESA)
);

-- 4. CREACIÓN DE LAS TABLAS DE HECHOS FÍSICAS (Conectadas a las SK_)
CREATE TABLE IF NOT EXISTS ORO.HECHO_OFERTA_TURISTICA (
    ID_REGISTRO         SERIAL,
    FECHA_PROCESO       DATE            NOT NULL,
    SK_EMPRESA          INTEGER         NOT NULL,
    SK_CIUDAD           INTEGER         NOT NULL,
    TIPO_SERVICIO       VARCHAR(20)     NOT NULL,
    ID_SERVICIO_ORIGEN  VARCHAR(10)     NOT NULL,
    PRECIO              NUMERIC(12,0)   NOT NULL,
    BLOQUE_CAPACIDAD    VARCHAR(30)     NOT NULL,
    DISPONIBLE          BOOLEAN         NOT NULL,
    PRIMARY KEY (ID_REGISTRO),
    FOREIGN KEY (SK_EMPRESA) REFERENCES ORO.DIM_EMPRESAS(SK_EMPRESA),
    FOREIGN KEY (SK_CIUDAD) REFERENCES ORO.DIM_CIUDAD(SK_CIUDAD)
);

CREATE TABLE IF NOT EXISTS ORO.HECHO_PRODUCTO_ARTESANAL (
    ID_REGISTRO         SERIAL,
    FECHA_PROCESO       DATE            NOT NULL,
    SK_CIUDAD           INTEGER         NOT NULL,
    ID_PRODUCTO_ORIGEN  INTEGER         NOT NULL,
    NOM_PRODUCTO        VARCHAR(100)    NOT NULL,
    PROVEEDOR           VARCHAR(80)     NOT NULL,
    PRECIO_COP          NUMERIC(10,0)   NOT NULL,
    PRIMARY KEY (ID_REGISTRO),
    FOREIGN KEY (SK_CIUDAD) REFERENCES ORO.DIM_CIUDAD(SK_CIUDAD)
);

CREATE TABLE IF NOT EXISTS ORO.HECHO_EVENTOS_WHATSAPP (
    ID_REGISTRO         SERIAL,
    FECHA_PROCESO       DATE            NOT NULL,
    FECHA_HORA          TIMESTAMP       NOT NULL,
    SK_EMPRESA          INTEGER         NOT NULL,
    SK_CIUDAD           INTEGER         NOT NULL,
    CATEGORIA           VARCHAR(20)     NOT NULL,
    DISPOSITIVO         VARCHAR(255)    NOT NULL,
    PRIMARY KEY (ID_REGISTRO),
    FOREIGN KEY (SK_EMPRESA) REFERENCES ORO.DIM_EMPRESAS(SK_EMPRESA),
    FOREIGN KEY (SK_CIUDAD) REFERENCES ORO.DIM_CIUDAD(SK_CIUDAD)
);

-- 5. SCRIPT DE INYECCIÓN DE DATOS (Procesamiento Relacional de Oro)
-- ---------------------------------------------------------------------
BEGIN;

-- Cargar Departamento de Santander (Datos maestros DANE)
INSERT INTO ORO.DIM_DEPARTAMENTO (ID_DPTO, NOM_DEPARTAMENTO)
SELECT DISTINCT ID_DPTO, 'SANTANDER' FROM BRONCE.CIUDADES WHERE ID_DPTO IS NOT NULL
ON CONFLICT (ID_DPTO) DO NOTHING;

-- Cargar Ciudades vinculadas a la SK del Departamento
INSERT INTO ORO.DIM_CIUDAD (ID_CIUDAD, NOM_CIUDAD, SK_DEPARTAMENTO)
SELECT C.ID_CIUDAD, TRIM(C.NOM_CIUDAD), D.SK_DEPARTAMENTO
FROM BRONCE.CIUDADES C
JOIN ORO.DIM_DEPARTAMENTO D ON D.ID_DPTO = C.ID_DPTO
ON CONFLICT (ID_CIUDAD) DO NOTHING;

-- Cargar catálogo de Empresas limpias de Plata
INSERT INTO ORO.DIM_EMPRESAS (ID_EMPRESA, NOM_EMPRESA, TIPO_SERVICIO)
SELECT ID_EMPRESA, NOM_EMPRESA, TIPO_SERVICIO FROM PLATA.DIM_EMPRESAS
ON CONFLICT (ID_EMPRESA) DO NOTHING;

-- Cargar Hecho de Ofertas resolviendo llaves surrogadas y bloques de capacidad
INSERT INTO ORO.HECHO_OFERTA_TURISTICA (FECHA_PROCESO, SK_EMPRESA, SK_CIUDAD, TIPO_SERVICIO, ID_SERVICIO_ORIGEN, PRECIO, BLOQUE_CAPACIDAD, DISPONIBLE)
SELECT 
    H.FECHA_PROCESO, E.SK_EMPRESA, C.SK_CIUDAD, 'Hospedaje', H.ID_HOSPEDAJE, H.PRECIO_NOCHE,
    CASE 
        WHEN H.CAPACIDAD_MAX BETWEEN 1 AND 10 THEN '1-10 Personas'
        WHEN H.CAPACIDAD_MAX BETWEEN 11 AND 20 THEN '11-20 Personas'
        ELSE 'Más de 20 Personas'
    END,
    H.DISPONIBILIDAD
FROM PLATA.HIST_HOSPEDAJES H
JOIN ORO.DIM_EMPRESAS E ON E.ID_EMPRESA = H.ID_EMPRESA
JOIN ORO.DIM_CIUDAD C ON C.ID_CIUDAD = H.ID_CIUDAD
WHERE H.FECHA_PROCESO = CURRENT_DATE;

-- Cargar Hecho de Artesanías
INSERT INTO ORO.HECHO_PRODUCTO_ARTESANAL (FECHA_PROCESO, SK_CIUDAD, ID_PRODUCTO_ORIGEN, NOM_PRODUCTO, PROVEEDOR, PRECIO_COP)
SELECT A.FECHA_PROCESO, C.SK_CIUDAD, A.ID_PRODUCTO, A.NOM_PRODUCTO, A.PROVEEDOR, A.PRECIO_COP
FROM PLATA.HIST_ARTESANIAS A
JOIN ORO.DIM_CIUDAD C ON C.ID_CIUDAD = A.ID_CIUDAD
WHERE A.FECHA_PROCESO = CURRENT_DATE;

-- Cargar Hecho de interacciones de WhatsApp
INSERT INTO ORO.HECHO_EVENTOS_WHATSAPP (FECHA_PROCESO, FECHA_HORA, SK_EMPRESA, SK_CIUDAD, CATEGORIA, DISPOSITIVO)
SELECT W.FECHA_PROCESO, W.FECHA_HORA, E.SK_EMPRESA, C.SK_CIUDAD, W.CATEGORIA, W.DISPOSITIVO
FROM PLATA.FACT_EVENTOS_WHATSAPP W
JOIN ORO.DIM_EMPRESAS E ON E.ID_EMPRESA = W.ID_EMPRESA
JOIN ORO.DIM_CIUDAD C ON C.ID_CIUDAD = W.ID_CIUDAD
WHERE W.FECHA_PROCESO = CURRENT_DATE;

COMMIT;

-- 6. CAPA SEMÁNTICA: VISTA INDEXADA EXCLUSIVA PARA EL AGENTE DE IA (GROQ)
CREATE OR REPLACE VIEW ORO.BUSCADOR_IA_VIAJEROS AS
SELECT 
    O.TIPO_SERVICIO, O.ID_SERVICIO_ORIGEN AS ID, O.PRECIO, O.BLOQUE_CAPACIDAD, C.NOM_CIUDAD AS MUNICIPIO, E.NOM_EMPRESA AS PROVEEDOR
FROM ORO.HECHO_OFERTA_TURISTICA O
JOIN ORO.DIM_EMPRESAS E ON E.SK_EMPRESA = O.SK_EMPRESA
JOIN ORO.DIM_CIUDAD C ON C.SK_CIUDAD = O.SK_CIUDAD
WHERE O.FECHA_PROCESO = CURRENT_DATE AND O.DISPONIBLE = TRUE;