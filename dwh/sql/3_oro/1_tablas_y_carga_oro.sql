CREATE TABLE IF NOT EXISTS ORO.DIM_DEPARTAMENTO
(
    SK_DEPARTAMENTO     SERIAL PRIMARY KEY,
    ID_DPTO             VARCHAR(2)  NOT NULL UNIQUE,
    NOM_DEPARTAMENTO    VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS ORO.DIM_CIUDAD
(
    SK_CIUDAD           SERIAL PRIMARY KEY,
    ID_CIUDAD           VARCHAR(6)  NOT NULL UNIQUE,
    NOM_CIUDAD          VARCHAR(40) NOT NULL,
    SK_DEPARTAMENTO     INTEGER     NOT NULL REFERENCES ORO.DIM_DEPARTAMENTO(SK_DEPARTAMENTO)
);

CREATE TABLE IF NOT EXISTS ORO.DIM_HOSPEDAJE
(
    SK_HOSPEDAJE        SERIAL PRIMARY KEY,
    ID_HOSPEDAJE        VARCHAR(10) NOT NULL,
    ID_HIST_HOSPEDAJE   INTEGER UNIQUE,
    NOM_HOSPEDAJE       VARCHAR(100) NOT NULL,
    TIPO_HOSPEDAJE      VARCHAR(30)  NOT NULL,
    ID_EMPRESA          VARCHAR(10)  NOT NULL,
    ID_CIUDAD           VARCHAR(6)   NOT NULL,
    VIGENTE_DESDE       TIMESTAMP    NOT NULL,
    VIGENTE_HASTA       TIMESTAMP,
    ES_ACTUAL           BOOLEAN      NOT NULL,
    CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_ORO_HOSPEDAJE_ACTUAL
    ON ORO.DIM_HOSPEDAJE (ID_HOSPEDAJE)
    WHERE ES_ACTUAL;

CREATE TABLE IF NOT EXISTS ORO.DIM_RANGO_CAPACIDAD
(
    SK_RANGO_CAPACIDAD  SMALLINT PRIMARY KEY,
    NOM_RANGO           VARCHAR(20) NOT NULL UNIQUE,
    CAPACIDAD_DESDE     INTEGER     NOT NULL,
    CAPACIDAD_HASTA     INTEGER,
    CHECK (CAPACIDAD_HASTA IS NULL OR CAPACIDAD_HASTA >= CAPACIDAD_DESDE)
);

CREATE TABLE IF NOT EXISTS ORO.HECHO_CAPACIDAD_HOSPEDAJE
(
    SK_HOSPEDAJE        INTEGER PRIMARY KEY REFERENCES ORO.DIM_HOSPEDAJE(SK_HOSPEDAJE),
    SK_RANGO_CAPACIDAD  SMALLINT NOT NULL REFERENCES ORO.DIM_RANGO_CAPACIDAD(SK_RANGO_CAPACIDAD),
    CAPACIDAD_MAX       INTEGER  NOT NULL CHECK (CAPACIDAD_MAX > 0),
    PRECIO_NOCHE        NUMERIC(12,0) NOT NULL CHECK (PRECIO_NOCHE >= 0),
    ACCION_HISTORICA    VARCHAR(10),
    USUARIO_REGISTRO    VARCHAR(100)
);

BEGIN;

INSERT INTO ORO.DIM_DEPARTAMENTO (ID_DPTO, NOM_DEPARTAMENTO)
SELECT ID_DPTO, NOM_DPTO
FROM PLATA.DIM_DEPARTAMENTOS
ON CONFLICT (ID_DPTO) DO UPDATE
SET NOM_DEPARTAMENTO = EXCLUDED.NOM_DEPARTAMENTO;

INSERT INTO ORO.DIM_CIUDAD (ID_CIUDAD, NOM_CIUDAD, SK_DEPARTAMENTO)
SELECT C.ID_CIUDAD, C.NOM_CIUDAD, D.SK_DEPARTAMENTO
FROM PLATA.DIM_CIUDADES C
JOIN ORO.DIM_DEPARTAMENTO D ON D.ID_DPTO = C.ID_DPTO
ON CONFLICT (ID_CIUDAD) DO UPDATE
SET NOM_CIUDAD = EXCLUDED.NOM_CIUDAD,
    SK_DEPARTAMENTO = EXCLUDED.SK_DEPARTAMENTO;

INSERT INTO ORO.DIM_RANGO_CAPACIDAD
    (SK_RANGO_CAPACIDAD, NOM_RANGO, CAPACIDAD_DESDE, CAPACIDAD_HASTA)
VALUES
    (1, '1-10', 1, 10),
    (2, '11-20', 11, 20),
    (3, '21+', 21, NULL)
ON CONFLICT (SK_RANGO_CAPACIDAD) DO UPDATE
SET NOM_RANGO = EXCLUDED.NOM_RANGO,
    CAPACIDAD_DESDE = EXCLUDED.CAPACIDAD_DESDE,
    CAPACIDAD_HASTA = EXCLUDED.CAPACIDAD_HASTA;

-- Cierra la version que el historial de OLTP registra como anterior.
UPDATE ORO.DIM_HOSPEDAJE D
SET VIGENTE_HASTA = H.VIGENTE_HASTA,
    ES_ACTUAL = FALSE
FROM PLATA.HIST_CAMBIOS_HOSPEDAJE H
WHERE D.ID_HOSPEDAJE = H.ID_HOSPEDAJE
  AND D.VIGENTE_DESDE = H.VIGENTE_DESDE
  AND D.ES_ACTUAL;

INSERT INTO ORO.DIM_HOSPEDAJE
    (ID_HOSPEDAJE, ID_HIST_HOSPEDAJE, NOM_HOSPEDAJE, TIPO_HOSPEDAJE,
     ID_EMPRESA, ID_CIUDAD, VIGENTE_DESDE, VIGENTE_HASTA, ES_ACTUAL)
SELECT
    H.ID_HOSPEDAJE, H.ID_HIST_HOSPEDAJE, H.NOM_HOSPEDAJE, H.TIPO_HOSPEDAJE,
    H.ID_EMPRESA, H.ID_CIUDAD, H.VIGENTE_DESDE, H.VIGENTE_HASTA, FALSE
FROM PLATA.HIST_CAMBIOS_HOSPEDAJE H
ON CONFLICT (ID_HIST_HOSPEDAJE) DO UPDATE SET
    NOM_HOSPEDAJE = EXCLUDED.NOM_HOSPEDAJE,
    TIPO_HOSPEDAJE = EXCLUDED.TIPO_HOSPEDAJE,
    ID_EMPRESA = EXCLUDED.ID_EMPRESA,
    ID_CIUDAD = EXCLUDED.ID_CIUDAD,
    VIGENTE_DESDE = EXCLUDED.VIGENTE_DESDE,
    VIGENTE_HASTA = EXCLUDED.VIGENTE_HASTA,
    ES_ACTUAL = FALSE;

INSERT INTO ORO.DIM_HOSPEDAJE
    (ID_HOSPEDAJE, NOM_HOSPEDAJE, TIPO_HOSPEDAJE, ID_EMPRESA, ID_CIUDAD,
     VIGENTE_DESDE, VIGENTE_HASTA, ES_ACTUAL)
SELECT
    H.ID_HOSPEDAJE, H.NOM_HOSPEDAJE, H.TIPO_HOSPEDAJE, H.ID_EMPRESA, H.ID_CIUDAD,
    H.FECHA_MODIFICACION, NULL, TRUE
FROM PLATA.HOSPEDAJES_DISPONIBLES H
WHERE NOT EXISTS (
    SELECT 1
    FROM ORO.DIM_HOSPEDAJE D
    WHERE D.ID_HOSPEDAJE = H.ID_HOSPEDAJE
      AND D.ES_ACTUAL
      AND D.NOM_HOSPEDAJE = H.NOM_HOSPEDAJE
      AND D.TIPO_HOSPEDAJE = H.TIPO_HOSPEDAJE
      AND D.ID_EMPRESA = H.ID_EMPRESA
      AND D.ID_CIUDAD = H.ID_CIUDAD
);

INSERT INTO ORO.HECHO_CAPACIDAD_HOSPEDAJE
    (SK_HOSPEDAJE, SK_RANGO_CAPACIDAD, CAPACIDAD_MAX, PRECIO_NOCHE,
     ACCION_HISTORICA, USUARIO_REGISTRO)
SELECT
    D.SK_HOSPEDAJE,
    R.SK_RANGO_CAPACIDAD,
    H.CAPACIDAD_MAX,
    H.PRECIO_NOCHE,
    H.ACCION,
    H.USUARIO_REGISTRO
FROM PLATA.HIST_CAMBIOS_HOSPEDAJE H
JOIN ORO.DIM_HOSPEDAJE D ON D.ID_HIST_HOSPEDAJE = H.ID_HIST_HOSPEDAJE
JOIN ORO.DIM_RANGO_CAPACIDAD R
  ON H.CAPACIDAD_MAX >= R.CAPACIDAD_DESDE
 AND (R.CAPACIDAD_HASTA IS NULL OR H.CAPACIDAD_MAX <= R.CAPACIDAD_HASTA)
ON CONFLICT (SK_HOSPEDAJE) DO UPDATE SET
    SK_RANGO_CAPACIDAD = EXCLUDED.SK_RANGO_CAPACIDAD,
    CAPACIDAD_MAX = EXCLUDED.CAPACIDAD_MAX,
    PRECIO_NOCHE = EXCLUDED.PRECIO_NOCHE,
    ACCION_HISTORICA = EXCLUDED.ACCION_HISTORICA,
    USUARIO_REGISTRO = EXCLUDED.USUARIO_REGISTRO;

INSERT INTO ORO.HECHO_CAPACIDAD_HOSPEDAJE
    (SK_HOSPEDAJE, SK_RANGO_CAPACIDAD, CAPACIDAD_MAX, PRECIO_NOCHE)
SELECT
    D.SK_HOSPEDAJE,
    R.SK_RANGO_CAPACIDAD,
    H.CAPACIDAD_MAX,
    H.PRECIO_NOCHE
FROM PLATA.HOSPEDAJES_DISPONIBLES H
JOIN ORO.DIM_HOSPEDAJE D
  ON D.ID_HOSPEDAJE = H.ID_HOSPEDAJE
 AND D.ES_ACTUAL
JOIN ORO.DIM_RANGO_CAPACIDAD R
  ON H.CAPACIDAD_MAX >= R.CAPACIDAD_DESDE
 AND (R.CAPACIDAD_HASTA IS NULL OR H.CAPACIDAD_MAX <= R.CAPACIDAD_HASTA)
ON CONFLICT (SK_HOSPEDAJE) DO UPDATE SET
    SK_RANGO_CAPACIDAD = EXCLUDED.SK_RANGO_CAPACIDAD,
    CAPACIDAD_MAX = EXCLUDED.CAPACIDAD_MAX,
    PRECIO_NOCHE = EXCLUDED.PRECIO_NOCHE,
    ACCION_HISTORICA = NULL,
    USUARIO_REGISTRO = NULL;

COMMIT;