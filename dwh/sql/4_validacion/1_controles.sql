-- El total de filas de Bronce y Plata debe coincidir.
SELECT
    'HOSPEDAJES_DISPONIBLES' AS CONTROL,
    (SELECT COUNT(*) FROM BRONCE.HOSPEDAJE WHERE DISPONIBILIDAD) AS FILAS_BRONCE,
    (SELECT COUNT(*) FROM PLATA.HOSPEDAJES_DISPONIBLES) AS FILAS_PLATA,
    (SELECT COUNT(*) FROM BRONCE.HOSPEDAJE WHERE DISPONIBILIDAD) =
        (SELECT COUNT(*) FROM PLATA.HOSPEDAJES_DISPONIBLES) AS EN_SINCRO

UNION ALL

SELECT
    'HISTORIAL_HOSPEDAJE',
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_HOSPEDAJE
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true'),
    (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_HOSPEDAJE),
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_HOSPEDAJE
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true') =
        (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_HOSPEDAJE);

-- Revisa capacidad y precio antes de que las reglas de Plata oculten problemas.
SELECT
    'CAPACIDAD_HOSPEDAJE_NO_POSITIVA' AS CONTROL,
    COUNT(*) AS FILAS_CON_PROBLEMA,
    COUNT(*) > 0 AS HAY_ALERTA
FROM BRONCE.HOSPEDAJE
WHERE DISPONIBILIDAD AND CAPACIDAD_MAX <= 0

UNION ALL

SELECT
    'PRECIO_HOSPEDAJE_NO_POSITIVO',
    COUNT(*),
    COUNT(*) > 0
FROM BRONCE.HOSPEDAJE
WHERE DISPONIBILIDAD AND PRECIO_NOCHE <= 0;

SELECT
    'HOSPEDAJES_ACTUALES_SIN_VERSION_SCD2' AS CONTROL,
    COUNT(*) AS FILAS_CON_PROBLEMA,
    COUNT(*) > 0 AS HAY_ALERTA
FROM PLATA.HOSPEDAJES_DISPONIBLES H
WHERE NOT EXISTS (
    SELECT 1
    FROM ORO.DIM_HOSPEDAJE D
    WHERE D.ID_HOSPEDAJE = H.ID_HOSPEDAJE
      AND D.ES_ACTUAL
)

UNION ALL

SELECT
    'VERSIONES_SCD2_HOSPEDAJE_SOLAPADAS',
    COUNT(*),
    COUNT(*) > 0
FROM ORO.DIM_HOSPEDAJE A
JOIN ORO.DIM_HOSPEDAJE B
  ON B.ID_HOSPEDAJE = A.ID_HOSPEDAJE
 AND A.SK_HOSPEDAJE < B.SK_HOSPEDAJE
 AND A.VIGENTE_DESDE < COALESCE(B.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
 AND B.VIGENTE_DESDE < COALESCE(A.VIGENTE_HASTA, 'infinity'::TIMESTAMP)

UNION ALL

SELECT
    'HECHOS_CAPACIDAD_SIN_RANGO',
    COUNT(*),
    COUNT(*) > 0
FROM ORO.HECHO_CAPACIDAD_HOSPEDAJE F
LEFT JOIN ORO.DIM_RANGO_CAPACIDAD R
  ON R.SK_RANGO_CAPACIDAD = F.SK_RANGO_CAPACIDAD
 AND F.CAPACIDAD_MAX >= R.CAPACIDAD_DESDE
 AND (R.CAPACIDAD_HASTA IS NULL OR F.CAPACIDAD_MAX <= R.CAPACIDAD_HASTA)
WHERE R.SK_RANGO_CAPACIDAD IS NULL;
