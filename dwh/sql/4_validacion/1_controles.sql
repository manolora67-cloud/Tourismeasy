-- Compara las ofertas actuales y los historiales entre Bronce y Plata.
SELECT
    'HOSPEDAJES_DISPONIBLES' AS CONTROL,
    (SELECT COUNT(*) FROM BRONCE.HOSPEDAJE WHERE DISPONIBILIDAD) AS FILAS_BRONCE,
    (SELECT COUNT(*) FROM PLATA.HOSPEDAJES_DISPONIBLES) AS FILAS_PLATA,
    (SELECT COUNT(*) FROM BRONCE.HOSPEDAJE WHERE DISPONIBILIDAD) =
        (SELECT COUNT(*) FROM PLATA.HOSPEDAJES_DISPONIBLES) AS EN_SINCRO
UNION ALL
SELECT
    'TRANSPORTES_DISPONIBLES',
    (SELECT COUNT(*) FROM BRONCE.TRANSPORTE WHERE DISPONIBILIDAD),
    (SELECT COUNT(*) FROM PLATA.TRANSPORTES_DISPONIBLES),
    (SELECT COUNT(*) FROM BRONCE.TRANSPORTE WHERE DISPONIBILIDAD) =
        (SELECT COUNT(*) FROM PLATA.TRANSPORTES_DISPONIBLES)
UNION ALL
SELECT
    'PLANES_DISPONIBLES',
    (SELECT COUNT(*) FROM BRONCE.PLANES_TURISTICOS WHERE DISPONIBILIDAD),
    (SELECT COUNT(*) FROM PLATA.PLANES_DISPONIBLES),
    (SELECT COUNT(*) FROM BRONCE.PLANES_TURISTICOS WHERE DISPONIBILIDAD) =
        (SELECT COUNT(*) FROM PLATA.PLANES_DISPONIBLES)
UNION ALL
SELECT
    'PRODUCTOS_ARTESANALES',
    (SELECT COUNT(*) FROM BRONCE.PRODUCTOS_ARTESANALES),
    (SELECT COUNT(*) FROM PLATA.PRODUCTOS_ARTESANALES),
    (SELECT COUNT(*) FROM BRONCE.PRODUCTOS_ARTESANALES) =
        (SELECT COUNT(*) FROM PLATA.PRODUCTOS_ARTESANALES);

SELECT
    'HISTORIAL_HOSPEDAJE' AS CONTROL,
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_HOSPEDAJE
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true') AS FILAS_BRONCE,
    (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_HOSPEDAJE) AS FILAS_PLATA,
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_HOSPEDAJE
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true') =
        (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_HOSPEDAJE) AS EN_SINCRO
UNION ALL
SELECT
    'HISTORIAL_TRANSPORTE',
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_TRANSPORTE
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true'),
    (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_TRANSPORTE),
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_TRANSPORTE
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true') =
        (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_TRANSPORTE)
UNION ALL
SELECT
    'HISTORIAL_PLAN',
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_PLAN_TURISTICO
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true'),
    (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_PLAN),
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_PLAN_TURISTICO
     WHERE DATOS_SNAPSHOT->>'disponibilidad' = 'true') =
        (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_PLAN)
UNION ALL
SELECT
    'HISTORIAL_PRODUCTO_ARTESANAL',
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_PRODUCTO_ARTESANAL),
    (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_PRODUCTO),
    (SELECT COUNT(*) FROM BRONCE.HISTORICO_PRODUCTO_ARTESANAL) =
        (SELECT COUNT(*) FROM PLATA.HIST_CAMBIOS_PRODUCTO);

-- Revisa que los productos tengan persona artesana cuando el dato esta informado.
SELECT
    'PRODUCTOS_SIN_ARTESANO' AS CONTROL,
    COUNT(*) AS FILAS_CON_PROBLEMA,
    COUNT(*) > 0 AS HAY_ALERTA
FROM PLATA.PRODUCTOS_ARTESANALES
WHERE ID_ARTESANO IS NULL
UNION ALL
SELECT
    'PRODUCTOS_CON_ARTESANO_NO_ENCONTRADO',
    COUNT(*),
    COUNT(*) > 0
FROM PLATA.PRODUCTOS_ARTESANALES P
LEFT JOIN PLATA.ARTESANOS A ON A.ID_ARTESANO = P.ID_ARTESANO
WHERE P.ID_ARTESANO IS NOT NULL
  AND A.ID_ARTESANO IS NULL;

-- Verifica que cada oferta actual tenga una version actual en Oro.
SELECT 'HOSPEDAJE_SIN_VERSION_ACTUAL' AS CONTROL, COUNT(*) AS FILAS_CON_PROBLEMA,
       COUNT(*) > 0 AS HAY_ALERTA
FROM PLATA.HOSPEDAJES_DISPONIBLES H
WHERE NOT EXISTS (
    SELECT 1 FROM ORO.DIM_HOSPEDAJE D
    WHERE D.ID_HOSPEDAJE = H.ID_HOSPEDAJE AND D.ES_ACTUAL
)
UNION ALL
SELECT 'TRANSPORTE_SIN_VERSION_ACTUAL', COUNT(*), COUNT(*) > 0
FROM PLATA.TRANSPORTES_DISPONIBLES T
WHERE NOT EXISTS (
    SELECT 1 FROM ORO.DIM_TRANSPORTE D
    WHERE D.ID_TRANSPORTE = T.ID_TRANSPORTE AND D.ES_ACTUAL
)
UNION ALL
SELECT 'PLAN_SIN_VERSION_ACTUAL', COUNT(*), COUNT(*) > 0
FROM PLATA.PLANES_DISPONIBLES P
WHERE NOT EXISTS (
    SELECT 1 FROM ORO.DIM_PLAN_TURISTICO D
    WHERE D.ID_PLAN_TURISTICO = P.ID_PLAN_TURISTICO AND D.ES_ACTUAL
)
UNION ALL
SELECT 'PRODUCTO_SIN_VERSION_ACTUAL', COUNT(*), COUNT(*) > 0
FROM PLATA.PRODUCTOS_ARTESANALES P
WHERE NOT EXISTS (
    SELECT 1 FROM ORO.DIM_PRODUCTO_ARTESANAL D
    WHERE D.ID_PRODUCTO = P.ID_PRODUCTO AND D.ES_ACTUAL
);

-- Revisa que las versiones historicas no se crucen entre si.
SELECT 'VERSIONES_HOSPEDAJE_SOLAPADAS' AS CONTROL, COUNT(*) AS FILAS_CON_PROBLEMA,
       COUNT(*) > 0 AS HAY_ALERTA
FROM ORO.DIM_HOSPEDAJE A
JOIN ORO.DIM_HOSPEDAJE B
  ON B.ID_HOSPEDAJE = A.ID_HOSPEDAJE
 AND A.SK_HOSPEDAJE < B.SK_HOSPEDAJE
 AND A.VIGENTE_DESDE < COALESCE(B.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
 AND B.VIGENTE_DESDE < COALESCE(A.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
UNION ALL
SELECT 'VERSIONES_TRANSPORTE_SOLAPADAS', COUNT(*), COUNT(*) > 0
FROM ORO.DIM_TRANSPORTE A
JOIN ORO.DIM_TRANSPORTE B
  ON B.ID_TRANSPORTE = A.ID_TRANSPORTE
 AND A.SK_TRANSPORTE < B.SK_TRANSPORTE
 AND A.VIGENTE_DESDE < COALESCE(B.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
 AND B.VIGENTE_DESDE < COALESCE(A.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
UNION ALL
SELECT 'VERSIONES_PLAN_SOLAPADAS', COUNT(*), COUNT(*) > 0
FROM ORO.DIM_PLAN_TURISTICO A
JOIN ORO.DIM_PLAN_TURISTICO B
  ON B.ID_PLAN_TURISTICO = A.ID_PLAN_TURISTICO
 AND A.SK_PLAN_TURISTICO < B.SK_PLAN_TURISTICO
 AND A.VIGENTE_DESDE < COALESCE(B.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
 AND B.VIGENTE_DESDE < COALESCE(A.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
UNION ALL
SELECT 'VERSIONES_PRODUCTO_SOLAPADAS', COUNT(*), COUNT(*) > 0
FROM ORO.DIM_PRODUCTO_ARTESANAL A
JOIN ORO.DIM_PRODUCTO_ARTESANAL B
  ON B.ID_PRODUCTO = A.ID_PRODUCTO
 AND A.SK_PRODUCTO < B.SK_PRODUCTO
 AND A.VIGENTE_DESDE < COALESCE(B.VIGENTE_HASTA, 'infinity'::TIMESTAMP)
 AND B.VIGENTE_DESDE < COALESCE(A.VIGENTE_HASTA, 'infinity'::TIMESTAMP);
