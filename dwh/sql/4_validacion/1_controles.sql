-- Consultas de auditoria del proceso Bronce -> Plata.
-- Cada resultado debe mostrar EN_SINCRO = TRUE.

-- Compara el total actual de Bronce con la foto de hoy en Plata.
SELECT
    'HOSPEDAJE' AS TABLA,
    (SELECT COUNT(*) FROM BRONCE.HOSPEDAJE) AS FILAS_BRONCE,
    (
        SELECT COUNT(*)
        FROM PLATA.HIST_HOSPEDAJES
        WHERE FECHA_PROCESO = CURRENT_DATE
    ) AS FILAS_PLATA,
    (SELECT COUNT(*) FROM BRONCE.HOSPEDAJE) = (
        SELECT COUNT(*)
        FROM PLATA.HIST_HOSPEDAJES
        WHERE FECHA_PROCESO = CURRENT_DATE
    ) AS EN_SINCRO

UNION ALL

SELECT
    'PLANES',
    (SELECT COUNT(*) FROM BRONCE.PLANES_TURISTICOS),
    (
        SELECT COUNT(*)
        FROM PLATA.HIST_PLANES
        WHERE FECHA_PROCESO = CURRENT_DATE
    ),
    (SELECT COUNT(*) FROM BRONCE.PLANES_TURISTICOS) = (
        SELECT COUNT(*)
        FROM PLATA.HIST_PLANES
        WHERE FECHA_PROCESO = CURRENT_DATE
    )

UNION ALL

SELECT
    'TRANSPORTE',
    (SELECT COUNT(*) FROM BRONCE.TRANSPORTE),
    (
        SELECT COUNT(*)
        FROM PLATA.HIST_TRANSPORTES
        WHERE FECHA_PROCESO = CURRENT_DATE
    ),
    (SELECT COUNT(*) FROM BRONCE.TRANSPORTE) = (
        SELECT COUNT(*)
        FROM PLATA.HIST_TRANSPORTES
        WHERE FECHA_PROCESO = CURRENT_DATE
    );

-- Cuenta precios negativos y capacidades en cero en las fotos de hoy.
-- HAY_ALERTA = TRUE indica que se encontraron filas para revisar.
SELECT
    'PRECIO_HOSPEDAJE_NEGATIVO' AS CONTROL,
    COUNT(*) AS FILAS_CON_PROBLEMA,
    COUNT(*) > 0 AS HAY_ALERTA
FROM PLATA.HIST_HOSPEDAJES
WHERE FECHA_PROCESO = CURRENT_DATE
  AND PRECIO_NOCHE < 0

UNION ALL

SELECT
    'CAPACIDAD_HOSPEDAJE_CERO',
    COUNT(*),
    COUNT(*) > 0
FROM PLATA.HIST_HOSPEDAJES
WHERE FECHA_PROCESO = CURRENT_DATE
  AND CAPACIDAD_MAX = 0

UNION ALL

SELECT
    'PRECIO_PLAN_NEGATIVO',
    COUNT(*),
    COUNT(*) > 0
FROM PLATA.HIST_PLANES
WHERE FECHA_PROCESO = CURRENT_DATE
  AND PRECIO_PLAN < 0

UNION ALL

SELECT
    'PRECIO_TRANSPORTE_NEGATIVO',
    COUNT(*),
    COUNT(*) > 0
FROM PLATA.HIST_TRANSPORTES
WHERE FECHA_PROCESO = CURRENT_DATE
  AND PRECIO < 0

UNION ALL

SELECT
    'PRECIO_ARTESANIA_NEGATIVO',
    COUNT(*),
    COUNT(*) > 0
FROM PLATA.HIST_ARTESANIAS
WHERE FECHA_PROCESO = CURRENT_DATE
  AND PRECIO_COP < 0;
