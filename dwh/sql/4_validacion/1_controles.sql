-- Ejecutar despues de cargar las capas plata y oro.
-- No modifica los datos: solo muestra resultados para revisar.

-- 1. Los conteos de plata y oro deben coincidir: CORRECTO debe ser TRUE.
SELECT
    'OFERTAS' AS VALIDACION,
    (SELECT COUNT(*) FROM PLATA.OFERTA_SNAPSHOT) AS FILAS_PLATA,
    (SELECT COUNT(*) FROM ORO.HECHO_OFERTA_TURISTICA) AS FILAS_ORO,
    (SELECT COUNT(*) FROM PLATA.OFERTA_SNAPSHOT)
        = (SELECT COUNT(*) FROM ORO.HECHO_OFERTA_TURISTICA) AS CORRECTO
UNION ALL
SELECT
    'PRODUCTOS',
    (SELECT COUNT(*) FROM PLATA.PRODUCTO_SNAPSHOT),
    (SELECT COUNT(*) FROM ORO.HECHO_PRODUCTO_ARTESANAL),
    (SELECT COUNT(*) FROM PLATA.PRODUCTO_SNAPSHOT)
        = (SELECT COUNT(*) FROM ORO.HECHO_PRODUCTO_ARTESANAL)
UNION ALL
SELECT
    'RESENAS',
    (SELECT COUNT(*) FROM PLATA.RESENA),
    (SELECT COUNT(*) FROM ORO.HECHO_RESENAS),
    (SELECT COUNT(*) FROM PLATA.RESENA)
        = (SELECT COUNT(*) FROM ORO.HECHO_RESENAS);

-- 2. Cada fotografia de producto debe encontrar una version dimensional.
-- El resultado esperado es cero.
SELECT COUNT(*) AS PRODUCTOS_SIN_VERSION
FROM PLATA.PRODUCTO_SNAPSHOT P
LEFT JOIN ORO.DIM_PRODUCTO D
    ON D.ID_PRODUCTO_ORIGEN = P.ID_PRODUCTO_ORIGEN
   AND P.FECHA_SNAPSHOT >= D.FECHA_INICIO
   AND P.FECHA_SNAPSHOT < D.FECHA_FIN
WHERE D.SK_PRODUCTO IS NULL;

-- 3. Una empresa vigente debe terminar en la fecha lejana acordada.
-- El resultado esperado es cero.
SELECT COUNT(*) AS EMPRESAS_VIGENTES_CON_FECHA_INCORRECTA
FROM ORO.DIM_EMPRESA
WHERE ES_VIGENTE = TRUE
  AND FECHA_FIN <> TIMESTAMP '9999-12-31 00:00:00';

-- 4. Debe existir como maximo una version vigente por empresa.
-- Esta consulta debe devolver cero filas.
SELECT ID_EMPRESA, COUNT(*) AS VERSIONES_VIGENTES
FROM ORO.DIM_EMPRESA
WHERE ES_VIGENTE = TRUE
GROUP BY ID_EMPRESA
HAVING COUNT(*) > 1;

-- 5. Debe existir como maximo una version vigente por producto.
-- Esta consulta debe devolver cero filas.
SELECT ID_PRODUCTO_ORIGEN, COUNT(*) AS VERSIONES_VIGENTES
FROM ORO.DIM_PRODUCTO
WHERE ES_VIGENTE = TRUE
GROUP BY ID_PRODUCTO_ORIGEN
HAVING COUNT(*) > 1;

-- 6. Los conteos de hechos sirven para revisar el resultado final.
SELECT 'OFERTAS' AS HECHO, COUNT(*) AS FILAS
FROM ORO.HECHO_OFERTA_TURISTICA
UNION ALL
SELECT 'PRODUCTOS', COUNT(*)
FROM ORO.HECHO_PRODUCTO_ARTESANAL
UNION ALL
SELECT 'RESENAS', COUNT(*)
FROM ORO.HECHO_RESENAS;
