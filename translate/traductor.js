        if (match) {
            return `Showing ${match[1]}–${match[2]} of ${match[3]} ${paginatedLabels[match[4].toLowerCase()]} · Page ${match[5]} of ${match[6]}`;
        }

        match = source.match(/^Se encontraron (\d+) rutas?$/);
        if (match) return `${match[1]} ${Number(match[1]) === 1 ? "route" : "routes"} found`;

        match = source.match(/^Se encontraron (\d+) (hospedajes?|plan(?:es)?|productos?|destinos?|municipios?|empresas?|artesanos?|reseñas?|festividades?)$/i);
