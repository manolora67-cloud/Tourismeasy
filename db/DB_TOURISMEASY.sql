CREATE TABLE IF NOT EXISTS USUARIOS
(
    ID_PERSONA      VARCHAR(10)   NOT NULL CHECK(LENGTH(ID_PERSONA) >= 6 AND ID_PERSONA ~ '^[0-9]+$'),
    NOM_PERSONA     VARCHAR(50)   NOT NULL CHECK(LENGTH(NOM_PERSONA) >= 2),
    APE_PERSONA     VARCHAR(50)   NOT NULL CHECK(LENGTH(APE_PERSONA) >= 2),
    NUM_CEL_PERSONA VARCHAR(20)   NOT NULL CHECK(NUM_CEL_PERSONA ~ '^\+?[0-9]{7,15}$'),
    EMAIL_LOGIN     VARCHAR       NOT NULL UNIQUE CHECK(EMAIL_LOGIN ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
