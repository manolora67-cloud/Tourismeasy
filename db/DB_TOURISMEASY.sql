CREATE TABLE IF NOT EXISTS CIUDADES
(
    ID_CIUDAD      VARCHAR(6)   NOT NULL CHECK(LENGTH(ID_CIUDAD) >= 5 AND ID_CIUDAD ~ '^[0-9A-Za-z]+$'),
    NOM_CIUDAD     VARCHAR(27)  NOT NULL CHECK(LENGTH(NOM_CIUDAD) >= 3),
    ID_DPTO        VARCHAR(2)   NOT NULL CHECK(LENGTH(ID_DPTO) = 2),
    PRIMARY KEY(ID_CIUDAD),
    FOREIGN KEY(ID_DPTO) REFERENCES DEPARTAMENTOS(ID_DPTO)
);

