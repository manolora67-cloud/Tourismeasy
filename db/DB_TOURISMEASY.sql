CREATE TABLE IF NOT EXISTS DEPARTAMENTOS
(
    ID_DPTO      VARCHAR(2)   NOT NULL CHECK(LENGTH(ID_DPTO) = 2 AND ID_DPTO ~ '^[0-9]{2}$'),
    NOM_DPTO     VARCHAR(18)  NOT NULL CHECK(LENGTH(NOM_DPTO) >= 3),
    PRIMARY KEY(ID_DPTO)
);

