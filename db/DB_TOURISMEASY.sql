    FOREIGN KEY(ID_EMPRESA) REFERENCES EMPRESAS(ID_EMPRESA),
    CONSTRAINT fk_transporte_ciudad_origen  FOREIGN KEY(ID_CIUDAD_ORIGEN) REFERENCES CIUDADES(ID_CIUDAD),
