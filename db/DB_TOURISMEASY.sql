--******************************
-- CONTENIDO ADMINISTRABLE DE PORTADA
--******************************

CREATE TABLE IF NOT EXISTS CONTENIDO_PORTADA
(
    CLAVE               VARCHAR(50)  CHECK (CLAVE ~ '^[a-z0-9-]{2,50}$'),
    IMAGEN              TEXT NOT NULL,
    TEXTO_ALT           VARCHAR(200) NOT NULL,
    INSIGNIA            VARCHAR(80),
    TITULO              VARCHAR(150) NOT NULL,
    DESCRIPCION         TEXT NOT NULL,
    ARTICULO            JSONB NOT NULL DEFAULT '{}'::JSONB CHECK (JSONB_TYPEOF(ARTICULO) = 'object'),
    ORDEN               DECIMAL(4,0) NOT NULL DEFAULT 0,
    PUBLICADO           BOOLEAN NOT NULL DEFAULT TRUE,
    MODIFICADO_POR      VARCHAR(10) REFERENCES USUARIOS(ID_PERSONA),
    FECHA_CREACION      TIMESTAMP NOT NULL DEFAULT NOW(),
    FECHA_ACTUALIZACION TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY(CLAVE)
);

CREATE INDEX IF NOT EXISTS IDX_CONTENIDO_PORTADA_PUBLICADO_ORDEN
    ON CONTENIDO_PORTADA (PUBLICADO, ORDEN, TITULO);

CREATE TABLE IF NOT EXISTS ESTADO_INICIAL_PORTADA
(
    ID                      DECIMAL(1,0) CHECK (ID = 1),
    DEFAULTS_CARGADOS       BOOLEAN    NOT NULL DEFAULT FALSE,
    PRIMARY KEY(ID)
);

INSERT INTO ESTADO_INICIAL_PORTADA (ID, DEFAULTS_CARGADOS)
VALUES (1, FALSE)
ON CONFLICT (ID) DO NOTHING;

