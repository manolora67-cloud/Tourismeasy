BEGIN;

CREATE TABLE IF NOT EXISTS CONFIGURACION_LIMITE_PERFIL_EMPRESA
(
    ID_CONFIG           SMALLINT     PRIMARY KEY CHECK (ID_CONFIG = 1),
    LIMITE_MENSUAL      SMALLINT     NOT NULL CHECK (LIMITE_MENSUAL BETWEEN 1 AND 10),
    ACTUALIZADO_POR     VARCHAR(10)  REFERENCES USUARIOS(ID_PERSONA),
    FECHA_ACTUALIZACION TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO CONFIGURACION_LIMITE_PERFIL_EMPRESA (ID_CONFIG, LIMITE_MENSUAL)
VALUES (1, 3)
ON CONFLICT (ID_CONFIG) DO NOTHING;

CREATE TABLE IF NOT EXISTS EDICIONES_PERFIL_EMPRESA
(
    ID_EMPRESA  VARCHAR(10) NOT NULL,
    MES         DATE         NOT NULL,
    CANTIDAD    SMALLINT     NOT NULL DEFAULT 0 CHECK (CANTIDAD BETWEEN 0 AND 10),
    PRIMARY KEY (ID_EMPRESA),
    FOREIGN KEY (ID_EMPRESA) REFERENCES USUARIOS_EMPRESA(ID_EMPRESA) ON DELETE CASCADE
);

INSERT INTO EDICIONES_PERFIL_EMPRESA (ID_EMPRESA, MES, CANTIDAD)
SELECT
    u.ID_EMPRESA,
    DATE_TRUNC('month', CURRENT_TIMESTAMP::TIMESTAMP)::DATE,
    CASE
        WHEN DATE_TRUNC('month', u.FECHA_ULTIMA_EDICION_PERFIL)
             = DATE_TRUNC('month', CURRENT_TIMESTAMP::TIMESTAMP)
        THEN 1
        ELSE 0
    END
FROM USUARIOS_EMPRESA u
ON CONFLICT (ID_EMPRESA) DO NOTHING;

COMMIT;
