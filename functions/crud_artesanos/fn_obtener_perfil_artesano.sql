CREATE OR REPLACE FUNCTION fn_obtener_perfil_artesano(
    p_id USUARIOS_ECOMMERCE.ID_PERSONA_ECOMMERCE%TYPE
)
RETURNS TABLE (
    id_persona_ecommerce USUARIOS_ECOMMERCE.ID_PERSONA_ECOMMERCE%TYPE,
    nombre PERSONAS_ECOMMERCE.NOM_PERSONA_ECOMMERCE%TYPE,
    apellido PERSONAS_ECOMMERCE.APE_PERSONA_ECOMMERCE%TYPE,
    telefono PERSONAS_ECOMMERCE.NUM_CEL_PERSONA_ECOMMERCE%TYPE,
    email USUARIOS_ECOMMERCE.EMAIL_LOGIN%TYPE,
    fecha_registro PERSONAS_ECOMMERCE.FECHA_REGISTRO%TYPE,
    estado USUARIOS_ECOMMERCE.ESTADO%TYPE
) AS
$$
BEGIN
    RETURN QUERY
    SELECT p.ID_PERSONA_ECOMMERCE,
           p.NOM_PERSONA_ECOMMERCE,
           p.APE_PERSONA_ECOMMERCE,
           p.NUM_CEL_PERSONA_ECOMMERCE,
           u.EMAIL_LOGIN,
           p.FECHA_REGISTRO,
           u.ESTADO
    FROM PERSONAS_ECOMMERCE p
    JOIN USUARIOS_ECOMMERCE u
      ON u.ID_PERSONA_ECOMMERCE = p.ID_PERSONA_ECOMMERCE
    WHERE p.ID_PERSONA_ECOMMERCE = p_id;
END;
$$
LANGUAGE plpgsql;
