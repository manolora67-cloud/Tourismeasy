CREATE OR REPLACE FUNCTION fn_historico_usuario_ecommerce()
RETURNS TRIGGER AS
$$
BEGIN
    IF TG_OP = 'UPDATE'
       AND (TO_JSONB(OLD) - 'CONTRASENA' - 'FECHA_MODIFICACION')
           IS NOT DISTINCT FROM (TO_JSONB(NEW) - 'CONTRASENA' - 'FECHA_MODIFICACION') THEN
        RETURN NULL;
    END IF;

    INSERT INTO HISTORICO_USUARIO_ECOMMERCE (
        ID_PERSONA_ECOMMERCE_ORIGINAL,
        DATOS_SNAPSHOT,
        ACCION
    )
    VALUES (
        OLD.ID_PERSONA_ECOMMERCE,
        (TO_JSONB(OLD) - 'CONTRASENA') || JSONB_BUILD_OBJECT('_tabla_origen', TG_TABLE_NAME),
        TG_OP
    );

    RETURN NULL;
END;
$$
LANGUAGE plpgsql;