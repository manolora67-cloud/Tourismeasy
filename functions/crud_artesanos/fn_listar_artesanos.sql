CREATE OR REPLACE FUNCTION fn_listar_artesanos(
    p_estado USUARIOS_ECOMMERCE.ESTADO%TYPE DEFAULT 'PENDIENTE'
)
RETURNS TABLE (
    id_persona_ecommerce      PERSONAS_ECOMMERCE.ID_PERSONA_ECOMMERCE%TYPE,
    nom_persona_ecommerce     PERSONAS_ECOMMERCE.NOM_PERSONA_ECOMMERCE%TYPE,
    ape_persona_ecommerce     PERSONAS_ECOMMERCE.APE_PERSONA_ECOMMERCE%TYPE,
    num_cel_persona_ecommerce PERSONAS_ECOMMERCE.NUM_CEL_PERSONA_ECOMMERCE%TYPE,
    email_persona_ecommerce   PERSONAS_ECOMMERCE.EMAIL_PERSONA_ECOMMERCE%TYPE,
    fecha_registro            PERSONAS_ECOMMERCE.FECHA_REGISTRO%TYPE,
    email_login               USUARIOS_ECOMMERCE.EMAIL_LOGIN%TYPE,
    estado                    USUARIOS_ECOMMERCE.ESTADO%TYPE
) AS
$$
BEGIN
    RETURN QUERY
    SELECT
        p.ID_PERSONA_ECOMMERCE, p.NOM_PERSONA_ECOMMERCE, p.APE_PERSONA_ECOMMERCE,
        p.NUM_CEL_PERSONA_ECOMMERCE, p.EMAIL_PERSONA_ECOMMERCE, p.FECHA_REGISTRO,
        u.EMAIL_LOGIN, u.ESTADO
    FROM PERSONAS_ECOMMERCE p
    JOIN USUARIOS_ECOMMERCE u ON u.ID_PERSONA_ECOMMERCE = p.ID_PERSONA_ECOMMERCE
    WHERE (p_estado = 'TODOS' OR u.ESTADO = p_estado)
    ORDER BY p.FECHA_REGISTRO DESC;

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_listar_artesanos - FK inválida: %', SQLERRM;
        RETURN;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_listar_artesanos - Check violado: %', SQLERRM;
        RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_listar_artesanos - Tabla bloqueada: %', SQLERRM;
        RETURN;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_listar_artesanos: %', SQLERRM;
        RETURN;
END;
$$
LANGUAGE plpgsql;