CREATE OR REPLACE FUNCTION fn_listar_clases_transporte()
RETURNS TABLE (
    id CLASE_SERVICIO_TRANSPORTE.ID_CLASE%TYPE,
    nombre CLASE_SERVICIO_TRANSPORTE.NOMBRE_CLASE%TYPE
) AS
$$
BEGIN
    RETURN QUERY SELECT c.ID_CLASE, c.NOMBRE_CLASE
    FROM CLASE_SERVICIO_TRANSPORTE c WHERE c.ACTIVO = TRUE ORDER BY c.NOMBRE_CLASE;
EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN RAISE NOTICE 'fn_listar_clases_transporte - FK inválida: %', SQLERRM; RETURN;
    WHEN CHECK_VIOLATION THEN RAISE NOTICE 'fn_listar_clases_transporte - Check violado: %', SQLERRM; RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN RAISE NOTICE 'fn_listar_clases_transporte - Tabla bloqueada: %', SQLERRM; RETURN;
    WHEN OTHERS THEN RAISE NOTICE 'fn_listar_clases_transporte: %', SQLERRM; RETURN;
END;
$$ LANGUAGE plpgsql;
