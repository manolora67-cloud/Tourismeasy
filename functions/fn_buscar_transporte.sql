CREATE FUNCTION fn_buscar_transporte(
    t_id_ciudad_origen TRANSPORTE.ID_CIUDAD_ORIGEN%TYPE DEFAULT NULL,
    t_id_ciudad_destino TRANSPORTE.ID_CIUDAD_DESTINO%TYPE DEFAULT NULL,
    t_fecha TRANSPORTE.FECHA_SALIDA%TYPE DEFAULT NULL,
    t_id_empresa TRANSPORTE.ID_EMPRESA%TYPE DEFAULT NULL,
    p_id_clase CLASE_SERVICIO_TRANSPORTE.ID_CLASE%TYPE DEFAULT NULL
)
RETURNS TABLE (
    id             TRANSPORTE.ID_TRANSPORTE%TYPE,
    empresa        EMPRESAS.NOM_EMPRESA%TYPE,
    origen         TRANSPORTE.ORIGEN%TYPE,
    destino        TRANSPORTE.DESTINO%TYPE,
    fecha_salida   TRANSPORTE.FECHA_SALIDA%TYPE,
    hora_salida    TRANSPORTE.HORA_SALIDA%TYPE,
    precio         TRANSPORTE.PRECIO%TYPE,
    descripcion    TRANSPORTE.DESCRIPCION%TYPE,
    img_url        TRANSPORTE.IMG_URL%TYPE,
    id_clase       CLASE_SERVICIO_TRANSPORTE.ID_CLASE%TYPE,
    nombre_clase   CLASE_SERVICIO_TRANSPORTE.NOMBRE_CLASE%TYPE,
    disponible     TRANSPORTE.DISPONIBILIDAD%TYPE,
    id_ciudad_origen TRANSPORTE.ID_CIUDAD_ORIGEN%TYPE,
    id_ciudad_destino TRANSPORTE.ID_CIUDAD_DESTINO%TYPE
) AS
$$
BEGIN
    IF t_id_empresa IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM EMPRESAS
           WHERE ID_EMPRESA = t_id_empresa AND TIPO_SERVICIO = 'TRANSPORTE'
       ) THEN
        RETURN;
    END IF;

    IF p_id_clase IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM CLASE_SERVICIO_TRANSPORTE
           WHERE ID_CLASE = p_id_clase
       ) THEN
        RETURN;
    END IF;

    RETURN QUERY
    SELECT
        t.ID_TRANSPORTE,
        e.NOM_EMPRESA,
        COALESCE(co.NOM_CIUDAD, t.ORIGEN),
        COALESCE(cd.NOM_CIUDAD, t.DESTINO),
        t.FECHA_SALIDA,
        t.HORA_SALIDA,
        t.PRECIO,
        t.DESCRIPCION,
        t.IMG_URL,
        cst.ID_CLASE,
        cst.NOMBRE_CLASE,
        t.DISPONIBILIDAD,
        t.ID_CIUDAD_ORIGEN,
        t.ID_CIUDAD_DESTINO
    FROM TRANSPORTE t
    JOIN EMPRESAS e ON e.ID_EMPRESA = t.ID_EMPRESA
    LEFT JOIN CIUDADES co ON co.ID_CIUDAD = t.ID_CIUDAD_ORIGEN
    LEFT JOIN CIUDADES cd ON cd.ID_CIUDAD = t.ID_CIUDAD_DESTINO
    LEFT JOIN TRANSPORTE_CLASE tc ON tc.ID_TRANSPORTE = t.ID_TRANSPORTE
    LEFT JOIN CLASE_SERVICIO_TRANSPORTE cst ON cst.ID_CLASE = tc.ID_CLASE
    WHERE t.DISPONIBILIDAD = TRUE
      AND (t_id_ciudad_origen IS NULL OR t.ID_CIUDAD_ORIGEN = t_id_ciudad_origen)
      AND (t_id_ciudad_destino IS NULL OR t.ID_CIUDAD_DESTINO = t_id_ciudad_destino)
      AND (t_fecha IS NULL OR t.FECHA_SALIDA = t_fecha)
      AND (t_id_empresa IS NULL OR t.ID_EMPRESA = t_id_empresa)
      AND (p_id_clase IS NULL OR tc.ID_CLASE = p_id_clase)
    ORDER BY t.FECHA_SALIDA, t.HORA_SALIDA;
END;
$$
LANGUAGE plpgsql;
