CREATE OR REPLACE FUNCTION fn_obtener_limite_edicion_perfil_empresa()
RETURNS TABLE (
    limite_mensual CONFIGURACION_LIMITE_PERFIL_EMPRESA.LIMITE_MENSUAL%TYPE,
    actualizado_por CONFIGURACION_LIMITE_PERFIL_EMPRESA.ACTUALIZADO_POR%TYPE,
    fecha_actualizacion CONFIGURACION_LIMITE_PERFIL_EMPRESA.FECHA_ACTUALIZACION%TYPE
)
LANGUAGE sql
AS $$
    SELECT LIMITE_MENSUAL, ACTUALIZADO_POR, FECHA_ACTUALIZACION
    FROM CONFIGURACION_LIMITE_PERFIL_EMPRESA
    WHERE ID_CONFIG = 1;
$$;
