CREATE OR REPLACE FUNCTION fn_listar_planes_empresa(
    p_id_empresa PLANES_TURISTICOS.ID_EMPRESA%TYPE
)
RETURNS TABLE (
    id             PLANES_TURISTICOS.ID_PLAN_TURISTICO%TYPE,
    nombre         PLANES_TURISTICOS.NOM_PLAN_TURISTICO%TYPE,
    duracion       PLANES_TURISTICOS.DURACION%TYPE,
    descripcion    PLANES_TURISTICOS.DESCRIPCION%TYPE,
    incluye        PLANES_TURISTICOS.INCLUYE%TYPE,
    id_tipo_plan   PLANES_TURISTICOS.ID_TIPO_PLAN%TYPE,
    tipo_plan      TIPOS_DE_PLAN_TURISTICO.NOM_TIPO_PLAN%TYPE,
    precio         PLANES_TURISTICOS.PRECIO_PLAN%TYPE,
    accesibilidad  PLANES_TURISTICOS.ACCESIBILIDAD%TYPE,
    disponible     PLANES_TURISTICOS.DISPONIBILIDAD%TYPE,
    id_ciudad      PLANES_TURISTICOS.ID_CIUDAD%TYPE,
    ciudad         CIUDADES.NOM_CIUDAD%TYPE,
    img_url        PLANES_TURISTICOS.IMG_URL%TYPE,
    fecha_creacion PLANES_TURISTICOS.FECHA_CREACION%TYPE
) AS
$$
BEGIN
    RETURN QUERY
    SELECT
        P.ID_PLAN_TURISTICO, P.NOM_PLAN_TURISTICO, P.DURACION, P.DESCRIPCION, P.INCLUYE,
        P.ID_TIPO_PLAN, T.NOM_TIPO_PLAN, P.PRECIO_PLAN, P.ACCESIBILIDAD, P.DISPONIBILIDAD,
        P.ID_CIUDAD, C.NOM_CIUDAD, P.IMG_URL, P.FECHA_CREACION
    FROM PLANES_TURISTICOS P
    LEFT JOIN TIPOS_DE_PLAN_TURISTICO T ON T.ID_TIPO_PLAN = P.ID_TIPO_PLAN
    LEFT JOIN CIUDADES C ON C.ID_CIUDAD = P.ID_CIUDAD
    WHERE P.ID_EMPRESA = p_id_empresa
    ORDER BY P.FECHA_CREACION DESC;

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_listar_planes_empresa - FK inválida: %', SQLERRM;
        RETURN;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_listar_planes_empresa - Check violado: %', SQLERRM;
        RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_listar_planes_empresa - Tabla bloqueada: %', SQLERRM;
        RETURN;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_listar_planes_empresa: %', SQLERRM;
        RETURN;
END;
$$
LANGUAGE plpgsql;
