CREATE OR REPLACE FUNCTION fn_actualizar_fecha_modificacion()
RETURNS TRIGGER AS
$$
BEGIN
    IF (TO_JSONB(OLD) - 'FECHA_MODIFICACION')
       IS DISTINCT FROM (TO_JSONB(NEW) - 'FECHA_MODIFICACION') THEN
        NEW.FECHA_MODIFICACION := NOW();
    ELSE
        NEW.FECHA_MODIFICACION := OLD.FECHA_MODIFICACION;
    END IF;

    RETURN NEW;
END;
$$
LANGUAGE plpgsql;