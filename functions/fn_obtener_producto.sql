CREATE OR REPLACE FUNCTION fn_obtener_producto(
    p_id         PRODUCTOS_ARTESANALES.ID_PRODUCTO%TYPE,
    p_id_persona PRODUCTOS_ARTESANALES.ID_PERSONA_ECOMMERCE%TYPE DEFAULT NULL
)
RETURNS TABLE (
    id_producto    PRODUCTOS_ARTESANALES.ID_PRODUCTO%TYPE,
    nom_producto   PRODUCTOS_ARTESANALES.NOM_PRODUCTO%TYPE,
    proveedor      PRODUCTOS_ARTESANALES.PROVEEDOR%TYPE,
    categoria      PRODUCTOS_ARTESANALES.CATEGORIA%TYPE,
    precio_cop     PRODUCTOS_ARTESANALES.PRECIO_COP%TYPE,
    id_ciudad      PRODUCTOS_ARTESANALES.ID_CIUDAD%TYPE,
    num_contacto   PRODUCTOS_ARTESANALES.NUM_CONTACTO%TYPE,
    descripcion    PRODUCTOS_ARTESANALES.DESCRIPCION%TYPE,
    img_url        PRODUCTOS_ARTESANALES.IMG_URL%TYPE,
    fecha_registro PRODUCTOS_ARTESANALES.FECHA_REGISTRO%TYPE
) AS
$$
BEGIN
    IF p_id_persona IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM USUARIOS_ECOMMERCE
        WHERE ID_PERSONA_ECOMMERCE = p_id_persona AND ESTADO = 'ACTIVO'
    ) THEN
        RETURN;
    END IF;

    RETURN QUERY
    SELECT
        p.ID_PRODUCTO, p.NOM_PRODUCTO, p.PROVEEDOR, p.CATEGORIA, p.PRECIO_COP,
        p.ID_CIUDAD, p.NUM_CONTACTO, p.DESCRIPCION, p.IMG_URL, p.FECHA_REGISTRO
    FROM PRODUCTOS_ARTESANALES p
    WHERE p.ID_PRODUCTO = p_id
      AND (p_id_persona IS NULL OR p.ID_PERSONA_ECOMMERCE = p_id_persona);

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_obtener_producto - FK inválida: %', SQLERRM;
        RETURN;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_obtener_producto - Check violado: %', SQLERRM;
        RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_obtener_producto - Tabla bloqueada: %', SQLERRM;
        RETURN;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_obtener_producto: %', SQLERRM;
        RETURN;
END;
$$
LANGUAGE plpgsql;