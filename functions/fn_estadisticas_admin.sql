CREATE OR REPLACE FUNCTION fn_estadisticas_admin()
RETURNS TABLE (
    empresas_registradas  INTEGER,
    calificacion_promedio DECIMAL,
    servicios_activos     INTEGER
) AS
$$
BEGIN
    RETURN QUERY
    SELECT
        (SELECT COUNT(*)::INTEGER FROM USUARIOS_EMPRESA WHERE ESTADO = 'ACTIVO'),
        (SELECT ROUND(AVG(PUNTUACION), 1) FROM RESENAS_PLATAFORMA),
        (
            (SELECT COUNT(*) FROM TRANSPORTE       WHERE DISPONIBILIDAD = TRUE) +
            (SELECT COUNT(*) FROM HOSPEDAJE         WHERE DISPONIBILIDAD = TRUE) +
            (SELECT COUNT(*) FROM PLANES_TURISTICOS WHERE DISPONIBILIDAD = TRUE)
        )::INTEGER;

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_estadisticas_admin - FK inválida: %', SQLERRM;
        RETURN QUERY SELECT NULL::INTEGER, NULL::DECIMAL, NULL::INTEGER;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_estadisticas_admin - Check violado: %', SQLERRM;
        RETURN QUERY SELECT NULL::INTEGER, NULL::DECIMAL, NULL::INTEGER;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_estadisticas_admin - Tabla bloqueada: %', SQLERRM;
        RETURN QUERY SELECT NULL::INTEGER, NULL::DECIMAL, NULL::INTEGER;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_estadisticas_admin: %', SQLERRM;
        RETURN QUERY SELECT NULL::INTEGER, NULL::DECIMAL, NULL::INTEGER;
END;
$$
LANGUAGE plpgsql;