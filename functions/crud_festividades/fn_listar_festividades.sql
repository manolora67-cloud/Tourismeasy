CREATE OR REPLACE FUNCTION fn_listar_festividades()
RETURNS TABLE (
    id_festividad FESTIVIDADES_SANTANDER.ID_FESTIVIDAD%TYPE,
    fecha_clave FESTIVIDADES_SANTANDER.FECHA_CLAVE%TYPE,
    subtitulo FESTIVIDADES_SANTANDER.SUBTITULO%TYPE,
    titulo FESTIVIDADES_SANTANDER.TITULO%TYPE,
    frase FESTIVIDADES_SANTANDER.FRASE%TYPE,
    emoji FESTIVIDADES_SANTANDER.EMOJI%TYPE,
    color_1 FESTIVIDADES_SANTANDER.COLOR_1%TYPE,
    color_2 FESTIVIDADES_SANTANDER.COLOR_2%TYPE,
    color_3 FESTIVIDADES_SANTANDER.COLOR_3%TYPE,
    bg_card FESTIVIDADES_SANTANDER.BG_CARD%TYPE,
    tipo FESTIVIDADES_SANTANDER.TIPO%TYPE,
    id_ciudad FESTIVIDADES_SANTANDER.ID_CIUDAD%TYPE,
    categoria FESTIVIDADES_SANTANDER.CATEGORIA%TYPE,
    img_url FESTIVIDADES_SANTANDER.IMG_URL%TYPE
) AS
$$
BEGIN
    RETURN QUERY
    SELECT f.ID_FESTIVIDAD, f.FECHA_CLAVE, f.SUBTITULO, f.TITULO, f.FRASE, f.EMOJI,
           f.COLOR_1, f.COLOR_2, f.COLOR_3, f.BG_CARD, f.TIPO, f.ID_CIUDAD,
           f.CATEGORIA, f.IMG_URL
    FROM FESTIVIDADES_SANTANDER f
    ORDER BY SUBSTRING(f.FECHA_CLAVE FROM 1 FOR 2),
             SUBSTRING(f.FECHA_CLAVE FROM 4 FOR 2), f.ID_FESTIVIDAD;

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_listar_festividades - FK inválida: %', SQLERRM;
        RETURN;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_listar_festividades - Check violado: %', SQLERRM;
        RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_listar_festividades - Tabla bloqueada: %', SQLERRM;
        RETURN;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_listar_festividades: %', SQLERRM;
        RETURN;
END;
$$
LANGUAGE plpgsql;
