CREATE OR REPLACE FUNCTION fn_obtener_config_admin(
    p_id USUARIOS.ID_PERSONA%TYPE
)
RETURNS TABLE (
    ok                   BOOLEAN,
    mensaje              TEXT,
    notif_reservas       CONFIG_ADMIN.NOTIF_NUEVAS_RESERVAS%TYPE,
    notif_cancelaciones  CONFIG_ADMIN.NOTIF_CANCELACIONES%TYPE,
    notif_resenas        CONFIG_ADMIN.NOTIF_NUEVAS_RESENAS%TYPE,
    notif_boletin        CONFIG_ADMIN.NOTIF_BOLETIN_MENSUAL%TYPE,
    tema_oscuro          CONFIG_ADMIN.TEMA_OSCURO%TYPE
) AS
$$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM USUARIOS WHERE ID_PERSONA = p_id) THEN
        RETURN QUERY SELECT FALSE, 'No autorizado.'::TEXT,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESERVAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_CANCELACIONES%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESENAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_BOLETIN_MENSUAL%TYPE,
            NULL::CONFIG_ADMIN.TEMA_OSCURO%TYPE;
        RETURN;
    END IF;

    INSERT INTO CONFIG_ADMIN (ID_USUARIO)
    VALUES (p_id)
    ON CONFLICT (ID_USUARIO) DO NOTHING;

    RETURN QUERY
    SELECT TRUE, 'OK'::TEXT,
        c.NOTIF_NUEVAS_RESERVAS, c.NOTIF_CANCELACIONES, c.NOTIF_NUEVAS_RESENAS,
        c.NOTIF_BOLETIN_MENSUAL, c.TEMA_OSCURO
    FROM CONFIG_ADMIN c
    WHERE c.ID_USUARIO = p_id
    LIMIT 1;

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_obtener_config_admin - FK inválida: %', SQLERRM;
        RETURN QUERY SELECT FALSE, 'Usuario no encontrado.'::TEXT,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESERVAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_CANCELACIONES%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESENAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_BOLETIN_MENSUAL%TYPE,
            NULL::CONFIG_ADMIN.TEMA_OSCURO%TYPE;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_obtener_config_admin - Check violado: %', SQLERRM;
        RETURN QUERY SELECT FALSE, 'Identificador de usuario inválido.'::TEXT,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESERVAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_CANCELACIONES%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESENAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_BOLETIN_MENSUAL%TYPE,
            NULL::CONFIG_ADMIN.TEMA_OSCURO%TYPE;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_obtener_config_admin - Fila bloqueada: %', SQLERRM;
        RETURN QUERY SELECT FALSE, 'La configuración está siendo actualizada, intenta de nuevo.'::TEXT,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESERVAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_CANCELACIONES%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESENAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_BOLETIN_MENSUAL%TYPE,
            NULL::CONFIG_ADMIN.TEMA_OSCURO%TYPE;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_obtener_config_admin: %', SQLERRM;
        RETURN QUERY SELECT FALSE, ('Error: ' || SQLERRM)::TEXT,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESERVAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_CANCELACIONES%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_NUEVAS_RESENAS%TYPE,
            NULL::CONFIG_ADMIN.NOTIF_BOLETIN_MENSUAL%TYPE,
            NULL::CONFIG_ADMIN.TEMA_OSCURO%TYPE;
END;
$$
LANGUAGE plpgsql;