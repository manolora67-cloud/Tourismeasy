CREATE OR REPLACE FUNCTION fn_crear_resena(
    p_rating     RESENAS_PLATAFORMA.PUNTUACION%TYPE,
    p_texto      RESENAS_PLATAFORMA.COMENTARIO%TYPE,
    p_nombre_anonimo RESENAS_PLATAFORMA.NOMBRE_ANONIMO%TYPE
)
RETURNS TABLE (
    ok         BOOLEAN,
    mensaje    TEXT,
    id_resena  RESENAS_PLATAFORMA.ID_RESENA%TYPE,
    fecha      RESENAS_PLATAFORMA.FECHA_CREACION%TYPE
) AS
$$
DECLARE
    v_id    RESENAS_PLATAFORMA.ID_RESENA%TYPE;
    v_fecha RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
BEGIN
    IF p_rating < 1 OR p_rating > 5 THEN
        RETURN QUERY SELECT FALSE, 'Puntuación inválida (1-5).'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
        RETURN;
    END IF;

    IF p_texto IS NULL OR LENGTH(p_texto) < 10 THEN
        RETURN QUERY SELECT FALSE, 'El comentario debe tener al menos 10 caracteres.'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
        RETURN;
    END IF;

    IF NULLIF(BTRIM(p_nombre_anonimo), '') IS NULL THEN
        RETURN QUERY SELECT FALSE, 'Ingresa tu nombre para publicar la reseña.'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
        RETURN;
    END IF;

    IF LENGTH(BTRIM(p_nombre_anonimo)) > 60 THEN
        RETURN QUERY SELECT FALSE, 'El nombre no puede superar 60 caracteres.'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
        RETURN;
    END IF;

    INSERT INTO RESENAS_PLATAFORMA AS rp (NOMBRE_ANONIMO, PUNTUACION, COMENTARIO)
    VALUES (BTRIM(p_nombre_anonimo), p_rating, p_texto)
    RETURNING rp.ID_RESENA, rp.FECHA_CREACION INTO v_id, v_fecha;

    RETURN QUERY SELECT TRUE, 'Reseña publicada.'::TEXT, v_id, v_fecha;

EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN
        RAISE NOTICE 'fn_crear_resena - FK inválida: %', SQLERRM;
        RETURN QUERY SELECT FALSE, 'No se pudo publicar la reseña.'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
    WHEN CHECK_VIOLATION THEN
        RAISE NOTICE 'fn_crear_resena - Check violado: %', SQLERRM;
        RETURN QUERY SELECT FALSE, 'La reseña no cumple los requisitos de puntuación o longitud.'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
    WHEN LOCK_NOT_AVAILABLE THEN
        RAISE NOTICE 'fn_crear_resena - Fila bloqueada: %', SQLERRM;
        RETURN QUERY SELECT FALSE, 'No se pudo publicar la reseña, intenta de nuevo.'::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
    WHEN OTHERS THEN
        RAISE NOTICE 'fn_crear_resena: %', SQLERRM;
        RETURN QUERY SELECT FALSE, ('Error: ' || SQLERRM)::TEXT, NULL::RESENAS_PLATAFORMA.ID_RESENA%TYPE, NULL::RESENAS_PLATAFORMA.FECHA_CREACION%TYPE;
END;
$$
LANGUAGE plpgsql;