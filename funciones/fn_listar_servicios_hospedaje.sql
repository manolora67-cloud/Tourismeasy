CREATE OR REPLACE FUNCTION fn_listar_servicios_hospedaje()
RETURNS TABLE (
    id SERVICIOS_HOSPEDAJE.ID_SERVICIO%TYPE,
    nombre SERVICIOS_HOSPEDAJE.NOMBRE_SERVICIO%TYPE
) AS
$$
BEGIN
    RETURN QUERY SELECT s.ID_SERVICIO, s.NOMBRE_SERVICIO
    FROM SERVICIOS_HOSPEDAJE s WHERE s.ACTIVO = TRUE ORDER BY s.NOMBRE_SERVICIO;
EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN RAISE NOTICE 'fn_listar_servicios_hospedaje - FK inválida: %', SQLERRM; RETURN;
    WHEN CHECK_VIOLATION THEN RAISE NOTICE 'fn_listar_servicios_hospedaje - Check violado: %', SQLERRM; RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN RAISE NOTICE 'fn_listar_servicios_hospedaje - Tabla bloqueada: %', SQLERRM; RETURN;
    WHEN OTHERS THEN RAISE NOTICE 'fn_listar_servicios_hospedaje: %', SQLERRM; RETURN;
END;
$$ LANGUAGE plpgsql;
