CREATE OR REPLACE FUNCTION fn_actualizar_config_empresa(
    p_id CONFIG_EMPRESA.ID_EMPRESA%TYPE,
    p_campo VARCHAR(30),
    p_valor CONFIG_EMPRESA.TEMA_OSCURO%TYPE
)
RETURNS BOOLEAN AS
$$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM USUARIOS_EMPRESA WHERE ID_EMPRESA = p_id) THEN RETURN FALSE; END IF;
    IF p_campo NOT IN ('notif_cancelaciones', 'notif_boletin', 'tema_oscuro') THEN RETURN FALSE; END IF;
    INSERT INTO CONFIG_EMPRESA (ID_EMPRESA) VALUES (p_id) ON CONFLICT (ID_EMPRESA) DO NOTHING;
    IF p_campo = 'notif_cancelaciones' THEN
        UPDATE CONFIG_EMPRESA SET NOTIF_CANCELACIONES = p_valor, FECHA_ACTUALIZACION = NOW() WHERE ID_EMPRESA = p_id;
    ELSIF p_campo = 'notif_boletin' THEN
        UPDATE CONFIG_EMPRESA SET NOTIF_BOLETIN = p_valor, FECHA_ACTUALIZACION = NOW() WHERE ID_EMPRESA = p_id;
    ELSE
        UPDATE CONFIG_EMPRESA SET TEMA_OSCURO = p_valor, FECHA_ACTUALIZACION = NOW() WHERE ID_EMPRESA = p_id;
    END IF;
    RETURN TRUE;
EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN RAISE NOTICE 'fn_actualizar_config_empresa - FK inválida: %', SQLERRM; RETURN FALSE;
    WHEN CHECK_VIOLATION THEN RAISE NOTICE 'fn_actualizar_config_empresa - Check violado: %', SQLERRM; RETURN FALSE;
    WHEN LOCK_NOT_AVAILABLE THEN RAISE NOTICE 'fn_actualizar_config_empresa - Fila bloqueada: %', SQLERRM; RETURN FALSE;
    WHEN OTHERS THEN RAISE NOTICE 'fn_actualizar_config_empresa: %', SQLERRM; RETURN FALSE;
END;
$$ LANGUAGE plpgsql;
