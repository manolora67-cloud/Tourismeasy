CREATE OR REPLACE FUNCTION fn_obtener_perfil_empresa(p_id EMPRESAS.ID_EMPRESA%TYPE)
RETURNS TABLE (
    nit EMPRESAS.ID_EMPRESA%TYPE,
    nombre EMPRESAS.NOM_EMPRESA%TYPE,
    email_inst EMPRESAS.EMAIL_INSTITU_EMPRESA%TYPE,
    contacto EMPRESAS.NUM_CONTACTO_EMPRESA%TYPE,
    servicio EMPRESAS.TIPO_SERVICIO%TYPE,
    id_ciudad EMPRESAS.ID_CIUDAD%TYPE,
    ciudad CIUDADES.NOM_CIUDAD%TYPE,
    departamento DEPARTAMENTOS.NOM_DPTO%TYPE,
    email_login USUARIOS_EMPRESA.EMAIL_LOGIN%TYPE,
    estado USUARIOS_EMPRESA.ESTADO%TYPE,
    fecha_registro USUARIOS_EMPRESA.FECHA_REGISTRO%TYPE
) AS
$$
BEGIN
    RETURN QUERY SELECT e.ID_EMPRESA, e.NOM_EMPRESA, e.EMAIL_INSTITU_EMPRESA,
        e.NUM_CONTACTO_EMPRESA, e.TIPO_SERVICIO, e.ID_CIUDAD, c.NOM_CIUDAD,
        d.NOM_DPTO, u.EMAIL_LOGIN, u.ESTADO, u.FECHA_REGISTRO
    FROM EMPRESAS e JOIN USUARIOS_EMPRESA u ON u.ID_EMPRESA = e.ID_EMPRESA
    LEFT JOIN CIUDADES c ON c.ID_CIUDAD = e.ID_CIUDAD
    LEFT JOIN DEPARTAMENTOS d ON d.ID_DPTO = c.ID_DPTO
    WHERE e.ID_EMPRESA = p_id;
EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN RAISE NOTICE 'fn_obtener_perfil_empresa - FK inválida: %', SQLERRM; RETURN;
    WHEN CHECK_VIOLATION THEN RAISE NOTICE 'fn_obtener_perfil_empresa - Check violado: %', SQLERRM; RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN RAISE NOTICE 'fn_obtener_perfil_empresa - Tabla bloqueada: %', SQLERRM; RETURN;
    WHEN OTHERS THEN RAISE NOTICE 'fn_obtener_perfil_empresa: %', SQLERRM; RETURN;
END;
$$ LANGUAGE plpgsql;
