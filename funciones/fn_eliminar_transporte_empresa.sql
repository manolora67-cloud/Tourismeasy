CREATE OR REPLACE FUNCTION fn_eliminar_transporte_empresa(
    p_id TRANSPORTE.ID_TRANSPORTE%TYPE,
    p_id_empresa TRANSPORTE.ID_EMPRESA%TYPE
)
RETURNS TRANSPORTE.DISPONIBILIDAD%TYPE AS
$$
BEGIN
    DELETE FROM TRANSPORTE t
    USING EMPRESAS e
    WHERE t.ID_TRANSPORTE = p_id
      AND t.ID_EMPRESA = p_id_empresa
      AND e.ID_EMPRESA = t.ID_EMPRESA
      AND e.TIPO_SERVICIO = 'TRANSPORTE';

    RETURN FOUND;
END;
$$ LANGUAGE plpgsql;
