CREATE OR REPLACE FUNCTION fn_obtener_config_empresa(p_id CONFIG_EMPRESA.ID_EMPRESA%TYPE)
RETURNS TABLE (
    notif_cancelaciones CONFIG_EMPRESA.NOTIF_CANCELACIONES%TYPE,
    notif_boletin CONFIG_EMPRESA.NOTIF_BOLETIN%TYPE,
    tema_oscuro CONFIG_EMPRESA.TEMA_OSCURO%TYPE
) AS
$$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM USUARIOS_EMPRESA WHERE ID_EMPRESA = p_id) THEN
        RETURN;
    END IF;
    INSERT INTO CONFIG_EMPRESA (ID_EMPRESA) VALUES (p_id) ON CONFLICT (ID_EMPRESA) DO NOTHING;
    RETURN QUERY SELECT c.NOTIF_CANCELACIONES, c.NOTIF_BOLETIN, c.TEMA_OSCURO
    FROM CONFIG_EMPRESA c WHERE c.ID_EMPRESA = p_id;
EXCEPTION
    WHEN FOREIGN_KEY_VIOLATION THEN RAISE NOTICE 'fn_obtener_config_empresa - FK inválida: %', SQLERRM; RETURN;
    WHEN CHECK_VIOLATION THEN RAISE NOTICE 'fn_obtener_config_empresa - Check violado: %', SQLERRM; RETURN;
    WHEN LOCK_NOT_AVAILABLE THEN RAISE NOTICE 'fn_obtener_config_empresa - Tabla bloqueada: %', SQLERRM; RETURN;
    WHEN OTHERS THEN RAISE NOTICE 'fn_obtener_config_empresa: %', SQLERRM; RETURN;
END;
$$ LANGUAGE plpgsql;
